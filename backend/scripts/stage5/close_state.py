"""Close out one Stage 5 state run with one command: the usage file, the search effect, a measures page and a
hand-over skeleton (three-state review 2026-11-13, change 5). Run it as the session's LAST act: a usage file taken
earlier misses the close-out (Missouri 1.4M weighted units, California 1.0M, Washington 0.6M).

usage: python3 -I scripts/stage5/close_state.py --profile <topic-profile.json> --state xx --session <main .jsonl>...
                                                [--leg A|B] [--batch xx-01] [--out <dir>] [--projects <dir>]... [--force]

--profile  the topic's profile (see session_card.py). It gives the topic key and the stage5 folder; nothing here
           names a topic, a ladder side or a rung.
--session  each main session's transcript, in order (session A, then B). ~/.claude/projects/<project>/<id>.jsonl
--leg      A = after set-up (usage only, written as usage-A.json); B (default) = after approval (everything).
--batch    the written batch under <stage5>/write/, for the approval time and the held list.
--out      default <stage5>/<xx>.

It reads files only and writes four, all under --out or <stage5>:
  usage-<xx>.json (or usage-A.json)   stage5_usage.py's own output, plus each session and each wave folder apart
  <stage5>/search-effect-<xx>.json    search_effect.py's own output, counted over the state's id list (leg B);
                                      under --out instead when --out is given
  MEASURES.md                         every number it can measure; `__` where a person must fill a row
  HANDOVER-<leg>-skeleton.md          headings with the paths filled in; never over a hand-written hand-over

What it cannot know is left as `__` with the evidence beside it: the gate runs, and which runner questions were
listed stops. It lists every question a session asked and every wait of five minutes or more that a runner message ended.
MEASURES.md is refused when a file of that name exists that this tool did not write (pass --force).
"""
import collections as C, csv, datetime, glob, json, os, re, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # -I drops the script dir
from _args import opt, opts
import stage5_usage as U
from session_card import load_profile

USAGE = 'close_state.py --profile <topic-profile.json> --state xx --session <main .jsonl>... [--leg A|B] [--batch xx-01] [--out <dir>] [--force]'
HERE = os.path.dirname(os.path.abspath(__file__))
MARK = '<!-- generated by close_state.py -->'
WAIT = 300  # seconds


def ts(s): return datetime.datetime.fromisoformat(s.replace('Z', '+00:00'))


def user_text(o):
    """The runner's own words in a transcript line, or '' (tool results, task notices and reminders are not the runner)."""
    if o.get('type') != 'user' or o.get('isSidechain'): return ''
    c = (o.get('message') or {}).get('content')
    if isinstance(c, list):
        if any(isinstance(x, dict) and x.get('type') == 'tool_result' for x in c): return ''
        c = ' '.join(x.get('text', '') for x in c if isinstance(x, dict) and x.get('type') == 'text')
    c = re.sub(r'<system-reminder>.*?</system-reminder>', '', c or '', flags=re.S).strip()
    return '' if c.startswith(('<task-notification', '<local-command', '<command-name', 'This session is being continued')) else c


def read_session(path):
    """(first time, last time, questions asked, waits a runner message ended) for one main transcript."""
    first = last = prev = None; asked, waits, open_q = [], [], set()
    for l in open(path):
        try: o = json.loads(l)
        except ValueError: continue
        t = o.get('timestamp')
        if not t: continue
        first = first or t; last = t
        for x in (o.get('message') or {}).get('content') or [] if o.get('type') == 'assistant' else []:
            if isinstance(x, dict) and x.get('type') == 'tool_use' and x.get('name') == 'AskUserQuestion':
                qs = (x.get('input') or {}).get('questions') or [{}]
                asked.append((t, re.sub(r'\s+', ' ', qs[0].get('question', ''))[:110], len(qs))); open_q.add(x.get('id'))
        said = user_text(o)
        c = (o.get('message') or {}).get('content') if o.get('type') == 'user' else None
        if isinstance(c, list) and any(isinstance(x, dict) and x.get('type') == 'tool_result' and x.get('tool_use_id') in open_q for x in c):
            said = 'an answer to a question'
        if said and prev and (ts(t) - ts(prev)).total_seconds() >= WAIT:
            waits.append((prev, t, round((ts(t) - ts(prev)).total_seconds() / 60), re.sub(r'\s+', ' ', said)[:70]))
        if o.get('type') in ('assistant', 'user'): prev = t  # other lines (snapshots, queue notes) are stamped when the runner types
    return first, last, asked, waits


def wave_dirs(S, xx):
    out = []
    for d in sorted(glob.glob(f'{S}/waves/{xx}-*')):
        for c in (d, os.path.join(d, 'out')):
            if os.path.isdir(c) and glob.glob(os.path.join(c, '*.result.json')): out.append(c)
    return out


def wave_units(d, roots):
    n = units = 0; missing = 0
    for f in glob.glob(os.path.join(d, '*.result.json')):
        try: sid = json.load(open(f)).get('session_id')
        except ValueError: sid = None
        p = U.find_session(sid, roots) if sid else None
        if not p: missing += 1; continue
        t, _, steps, _ = U.read(p)
        if steps: n += 1; units += U.units(t)
    return n, round(units), missing


def run(tool, *args):
    p = subprocess.run([sys.executable, '-I', os.path.join(HERE, tool), *args], capture_output=True, text=True)
    if p.returncode != 0: raise SystemExit(f'{tool} exit {p.returncode}: {(p.stderr or p.stdout)[-600:]}')
    return p.stdout


def k(n): return f'{n:,.0f}'
def m(n): return f'{n / 1e6:.2f}M'


def main():
    prof = load_profile(os.path.abspath(opt('--profile', required=True, usage=USAGE)))
    xx = opt('--state', required=True, usage=USAGE).lower()
    leg = (opt('--leg') or 'B').upper()
    sessions = [os.path.abspath(s) for s in opts('--session')]
    if not sessions or leg not in ('A', 'B'): raise SystemExit(USAGE)
    for s in sessions:
        if not os.path.exists(s): raise SystemExit(f'--session {s}: no such file')
    S, topic = prof['stage5'].rstrip('/'), prof['topic_key']
    out = opt('--out') or f'{S}/{xx}'
    os.makedirs(out, exist_ok=True)
    ids = f'{S}/batches/{xx}-ids.txt'
    if not os.path.exists(ids): raise SystemExit(f'{ids}: the state\'s id list is missing')
    people = len(open(ids).read().split())
    roots = opts('--projects') or ['~/.claude/projects', '~/.claude-ev/projects']
    waves = wave_dirs(S, xx)
    if leg == 'B' and not waves: raise SystemExit(f'no wave folder with *.result.json under {S}/waves/{xx}-*: nothing to measure')

    # 1. usage: stage5_usage.py's own file, then each session and wave folder apart
    usage_path = f'{out}/usage-{"A" if leg == "A" else xx}.json'
    effect_path = None
    args = [x for s in sessions for x in ('--session', s)] + [x for d in waves for x in ('--wave-dir', d)]
    run('stage5_usage.py', *args, *[x for r in opts('--projects') for x in ('--projects', r)], '--people', str(people), '--json', usage_path)
    usage = json.load(open(usage_path))
    per_session = []
    for s in sessions:
        t, _, steps, start = U.read(s); first, last, asked, waits = read_session(s)
        per_session.append({'path': s, 'units': round(U.units(t)), 'steps': steps, 'start_size': start, 'first': first, 'last': last,
                            'questions': [{'at': a, 'first_question': q, 'questions': n} for a, q, n in asked],
                            'waits': [{'from': a, 'to': b, 'minutes': mins, 'ended_by': said} for a, b, mins, said in waits]})
    per_wave = {}
    for d in waves:
        n, u, miss = wave_units(d, roots)
        name = os.path.basename(d if os.path.basename(d) != 'out' else os.path.dirname(d))
        per_wave[name] = {'agents': n, 'units': u, 'per_person': round(u / people), 'results_without_transcript': miss}
    usage.update({'people': people, 'sessions': per_session, 'waves': per_wave, 'taken_at': datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds')})
    json.dump(usage, open(usage_path, 'w'), indent=1)

    # 2. the search effect, over the state's own people
    effect = None
    if leg == 'B' and os.path.exists(f'{S}/search-plan-{xx}/search.tsv') and os.path.isdir(f'{S}/codes'):
        effect_path = f'{out}/search-effect-{xx}.json' if opt('--out') else f'{S}/search-effect-{xx}.json'
        run('search_effect.py', '--roster', f'{S}/roster.tsv', '--unit', f'state:{xx}', '--ids', ids, '--record-codes', f'{S}/record-codes',
            '--codes', f'{S}/codes', '--plan', f'{S}/search-plan-{xx}', '--json', effect_path)
        effect = json.load(open(effect_path))
    script = next((json.load(open(f)) for f in sorted(glob.glob(f'{S}/record-briefs-{xx}/*-script-summary.json'))), None)

    # 3. clock
    batch = opt('--batch'); B = f'{S}/write/{batch}' if batch else None
    start = min(p['first'] for p in per_session if p['first'])
    approved = f'{B}/readback-approved.txt' if B else None
    if approved and os.path.exists(approved):
        end, end_from = datetime.datetime.fromtimestamp(os.path.getmtime(approved), datetime.timezone.utc), f'`{batch}/readback-approved.txt`'
    else:
        end, end_from = ts(max(p['last'] for p in per_session if p['last'])), 'the last session\'s last step (no approval file found)'
    elapsed = (end - ts(start)).total_seconds() / 3600
    waited = sum(w['minutes'] for p in per_session for w in p['waits'] if ts(w['to']) <= end)
    held = len(open(f'{B}/held.txt').read().split('\n')) - 1 if B and os.path.exists(f'{B}/held.txt') else None
    gates = len(glob.glob(f'{B}/gate-output*.txt')) if B else 0

    # 4. MEASURES.md
    main_u = usage['main_units']; total = usage['total_units']
    L = [MARK, f'# {topic} · state:{xx} · measures (leg {leg})', '',
         f'Written {usage["taken_at"]} by `close_state.py`, as the session\'s last act. Sources: `{usage_path}`'
         + (f', `{effect_path}`' if effect else '') + '. Rows marked `__` need a person.', '',
         '| Measure | This state |', '|---|---|',
         f'| People | {people} |',
         f'| Weighted units per person | {k(total / people)} ({m(total)} / {people}) |',
         f'| Main-session share | {100 * main_u / total:.0f}% ({m(main_u)}, {usage["main_steps"]} steps) |']
    for i, p in enumerate(per_session):
        L.append(f'| Main session {i + 1} | {m(p["units"])}, {p["steps"]} steps, starting size {k(p["start_size"])} tokens |')
    if effect:
        c = effect['codings']
        L += [f'| Codings per person | {c["total"] / people:.2f} ({c["record_only"]} record-only + {c["second_pass"]} second pass, for {people}) |',
              f'| People searched | {effect["searched"]} (search list: {sum(1 for _ in open(f"{S}/search-plan-{xx}/search.tsv")) - 1}) |']
        rows = [f'{name}: {r["changed"]} of {r["searched"]}' for name, r in effect['by_record_result'].items() if name != 'no record']
        L.append(f'| Searched people whose code changed, by record result | {"; ".join(rows) or "none had a record code"} |')
        for g, r in (effect.get('controls') or {}).items(): L.append(f'| Control, rung {g} | {r["changed"]} of {r["searched"]} changed |')
        if not effect.get('controls'): L.append(f'| Control | {effect["control_changed"]} of {effect["control"]} changed |')
    if script:
        chk = script.get('check') or {}
        L += [f'| Script-coded share of the record pass | script {script["script"]} of {script["script"] + script["opus"]}, Opus lane {script["opus"]}; no record {script.get("no_record", "?")} |',
              f'| Standing check | {chk.get("agreed", "__")} of {chk.get("compared", "__")} |',
              f'| People sent to Opus, by reason (reasons overlap) | {"; ".join(f"{a} {b}" for a, b in (script.get("lanes") or {}).items()) or "none"} |']
    asked = [(i + 1, q) for i, p in enumerate(per_session) for q in p['questions']]
    L += [f'| Gate runs | __ ({gates} `gate-output*.txt` file(s) in the batch) |' if B else '| Gate runs | __ |',
          f'| Runner stops | __ (the sessions asked {len(asked)} time(s); mark each below as listed or unlisted) |',
          f'| Elapsed, first session start to {"approved" if "readback" in end_from else "end"} | {elapsed:.2f} h, of which {waited / 60:.2f} h waiting on a runner message (end taken from {end_from}) |']
    if held is not None: L.append(f'| People held | {held} |')
    L += ['', '## Cost by part', '', '| Part | Agents | Weighted units | Per person |', '|---|---|---|---|']
    for i, p in enumerate(per_session): L.append(f'| Main session {i + 1} | 1 | {m(p["units"])} | {k(p["units"] / people)} |')
    for name, w in per_wave.items(): L.append(f'| `{name}` | {w["agents"]} | {m(w["units"])} | {k(w["per_person"])} |')
    L.append(f'| **Total** | | **{m(total)}** | **{k(total / people)}** |')
    miss = usage.get('wave_results_without_transcript') or []
    if miss: L += ['', f'⚠ {len(miss)} wave result(s) have no transcript on this machine, so their cost is not counted: {", ".join(miss[:5])}']
    L += ['', '## Questions the sessions asked', '']
    L += [f'- session {i}, {q["at"][:16]}Z: {q["first_question"]}' + (f' (+{q["questions"] - 1} more)' if q['questions'] > 1 else '') + ' — listed stop __ / unlisted, cause: __' for i, q in asked] or ['- none']
    L += ['', f'## Waits of {WAIT // 60} minutes or more that a runner message ended', '']
    L += [f'- session {i + 1}: {w["minutes"]} min, {w["from"][11:16]}Z to {w["to"][11:16]}Z, ended by "{w["ended_by"]}"' for i, p in enumerate(per_session) for w in p['waits']] or ['- none']
    L.append('')
    path = f'{out}/MEASURES.md'
    if os.path.exists(path) and MARK not in open(path).read() and '--force' not in sys.argv:
        raise SystemExit(f'{path} exists and was not written by this tool. Pass --force to replace it. ({usage_path} was written.)')
    open(path, 'w').write('\n'.join(L))

    # 5. hand-over skeleton
    sk = f'{out}/HANDOVER-{leg}-skeleton.md'
    H = [f'# {topic} · state:{xx} · session {leg} hand-over (skeleton: copy to HANDOVER-{leg}.md and fill)', '',
         f'- Stage 5 folder: `{S}`', f'- Profile: `{os.path.abspath(opt("--profile"))}`', f'- People: {people} (`{ids}`)',
         f'- Usage: `{usage_path}` ({m(total)}, {k(total / people)} per person)']
    H += [f'- Session {i + 1} transcript: `{p["path"]}` ({(p["first"] or "")[:16]}Z to {(p["last"] or "")[:16]}Z)' for i, p in enumerate(per_session)]
    H += [f'- Wave folders: {", ".join(f"`{d}`" for d in waves) or "none"}']
    if B: H += [f'- Batch: `{B}`' + (f', held {held}' if held is not None else '')]
    H += ['', '## To fill', '', '1. What was done, with counts.', '2. Branch, commits, and whether it is pushed.', '3. People held, and why.',
          '4. Legislature quirks the next session needs.', '5. Open items and anything the runner said to revisit.', '6. Tool findings.', '']
    open(sk, 'w').write('\n'.join(H))
    print(f'{topic} state:{xx} leg {leg}: {m(total)}, {k(total / people)} per person; main session {100 * main_u / total:.0f}%')
    print(f'wrote {usage_path}, {path}, {sk}' + (f', {effect_path}' if effect else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main())
