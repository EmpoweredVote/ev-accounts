#!/usr/bin/env node
/**
 * check-auth-client-isolation — a session-establishing GoTrue call must never
 * run on a shared DATA client.
 *
 * 🔴 WHAT THIS EXISTS TO PREVENT, AND WHY A REVIEWER CANNOT.
 * On 2026-09-10 signed-in users could not save Empowered Compass answers. The
 * three write RPCs returned "permission denied for function" even though
 * service_role holds EXECUTE on them. The cause was not a grant: authService
 * called `supabaseAdmin.auth.signInWithPassword(...)`. supabase-js stores the
 * session returned by a sign-in ON THE CLIENT THAT MADE THE CALL, and its
 * `_getAccessToken()` then returns that session's token in preference to the
 * API key. So every `adminRpc()` after any login authenticated as the
 * last-logged-in user (role `authenticated`), not service_role.
 *
 * It compiles, it passes unit tests, and it is invisible in review — the wrong
 * client is a one-word difference and the damage only appears at runtime, after
 * a login, against a shared singleton. So the gate is the reviewer.
 *
 * THE RULE: the methods that STORE a session on the client
 * (signInWithPassword, signUp, signInWithOtp, signInWithOAuth,
 * signInWithIdToken, verifyOtp, refreshSession, setSession,
 * exchangeCodeForSession) may not be called on a shared data/service client —
 * `supabaseAdmin`, `supabaseAnon`, or `supabaseService`. Run them on a dedicated
 * auth-only client (e.g. `supabaseAuth`) that is never used for `.from()` /
 * `.rpc()`, so the session it accumulates is inert.
 *
 * ⚠ ADMIN AND INTROSPECTION CALLS ARE FINE. `auth.admin.*` (getUserById,
 * listUsers, createUser, updateUserById, deleteUser, signOut) and
 * `auth.getUser(token)` do NOT store a session, so they stay on supabaseAdmin.
 * They are not in the method list below.
 *
 * Dependency-free: node:fs + node:path only. Exit 0 = clean, exit 1 = a session
 * call on a shared data client.
 */

import { readdirSync, readFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = join(process.cwd(), 'src');

/** Shared clients that are used for data (.from/.rpc) and must stay session-free. */
const DATA_CLIENTS = ['supabaseAdmin', 'supabaseAnon', 'supabaseService'];

/** GoTrue methods that STORE a session on the calling client. */
const SESSION_METHODS = [
  'signInWithPassword',
  'signUp',
  'signInWithOtp',
  'signInWithOAuth',
  'signInWithIdToken',
  'verifyOtp',
  'refreshSession',
  'setSession',
  'exchangeCodeForSession',
];

// e.g. `supabaseAdmin.auth.signInWithPassword(` — whitespace-tolerant.
const OFFENDER = new RegExp(
  `\\b(${DATA_CLIENTS.join('|')})\\s*\\.\\s*auth\\s*\\.\\s*(${SESSION_METHODS.join('|')})\\s*\\(`,
  'g'
);

function sourceFiles(root) {
  return readdirSync(root, { recursive: true, encoding: 'utf8' })
    .filter((f) => f.endsWith('.ts'))
    .filter((f) => !f.endsWith('.test.ts'))
    // Generated by `supabase gen types`; names every function in the schema.
    .filter((f) => f.split(sep).join('/') !== 'types/database.types.ts')
    .map((f) => join(root, f));
}

/**
 * Blank comments to spaces (not remove them) so line numbers survive and the
 * many prose mentions of these method names — including this file's siblings and
 * the supabaseAuth doc-comment in lib/supabase.ts — cannot score as calls.
 */
function blankComments(text) {
  const blank = (m) => m.replace(/[^\n]/g, ' ');
  return text
    .replace(/\/\*[\s\S]*?\*\//g, blank)
    .replace(/--[^\n]*/g, blank)
    .replace(/\/\/[^\n]*/g, blank);
}

function scan(root) {
  const offenders = [];
  for (const path of sourceFiles(root)) {
    const raw = readFileSync(path, 'utf8');
    const rel = relative(root, path).split(sep).join('/');
    const code = blankComments(raw);
    OFFENDER.lastIndex = 0;
    let m;
    while ((m = OFFENDER.exec(code)) !== null) {
      const line = code.slice(0, m.index).split('\n').length;
      offenders.push({ rel, line, client: m[1], method: m[2] });
    }
  }
  return offenders;
}

const offenders = scan(ROOT);

if (offenders.length === 0) {
  console.log(
    'auth client isolation — no session-establishing GoTrue call runs on a shared data client.'
  );
  process.exit(0);
}

const byFile = new Map();
for (const o of offenders) {
  if (!byFile.has(o.rel)) byFile.set(o.rel, []);
  byFile.get(o.rel).push(o);
}

console.error(
  `auth client isolation — ${offenders.length} session call(s) in ${byFile.size} file(s) run on a shared data client:`
);
for (const [rel, list] of byFile) {
  console.error(`  ${rel}`);
  for (const o of list) {
    console.error(`    · ${rel}:${o.line} — ${o.client}.auth.${o.method}(...) stores a session on ${o.client}`);
  }
}
console.error('');
console.error('supabase-js keeps the session from a sign-in on the calling client, and every');
console.error('later .rpc()/.from() then authenticates as that user instead of the API key.');
console.error('On a shared data client this makes every request after a login run under the');
console.error('wrong role — the 2026-09-10 compass-write outage.');
console.error('');
console.error('Fix: run this call on a dedicated auth-only client (supabaseAuth) that is never');
console.error('used for .from()/.rpc(). auth.admin.* and auth.getUser(token) store no session');
console.error('and may stay on supabaseAdmin.');
process.exit(1);
