#!/usr/bin/env node
/**
 * check-postgis-spatial-ref-guard — keep the two SQL patterns that would revive a
 * dormant risk out of the live query paths.
 *
 * 🔴 WHAT THIS EXISTS TO PREVENT, AND WHY IT IS A TRIPWIRE RATHER THAN A BUG FIX.
 * PostGIS is installed in the `public` schema on this project (Supabase
 * `kxsdzaojfaibhuzmclfq`) and CANNOT be moved by us — the extension is owned by
 * `supabase_admin` and is non-relocatable. A side effect is that `anon` and
 * `authenticated` hold INSERT/UPDATE/DELETE/TRUNCATE on `public.spatial_ref_sys`,
 * with RLS off, and we cannot REVOKE it (the grantor is `supabase_admin`). See
 * ev-cto decision 0006 — the founder ACCEPTED this risk (Option A) on the measured
 * grounds that nothing load-bearing reads that table today.
 *
 * "Nothing reads it" is the whole basis of that decision, and it is true only by a
 * fact about our SQL: the live district lookups use a FIXED SRID 4326 with
 * `ST_SetSRID` + `ST_Covers`/`ST_Contains`/`ST_Intersects`, and those functions
 * never touch `spatial_ref_sys`. TWO patterns break that, because both read
 * `spatial_ref_sys` to look a coordinate system up:
 *
 *   1. `ST_Transform(...)`      — reprojects between SRIDs.
 *   2. a `::geography` cast     — geography operations resolve the datum via the table.
 *
 * The day either lands in a live query path, the anon write grant we cannot revoke
 * turns from cosmetic into a real availability risk (someone empties or corrupts
 * the reference table and the query breaks or returns wrong distances). That
 * re-opens decision 0006, so it must be a DELIBERATE, signed-off change — not
 * something that slips in inside an unrelated PR.
 *
 * ⚠ SCOPE AND A DELIBERATE GRANDFATHER.
 *   · backend/src/**            — the live Express API. Scanned whole; clean today.
 *   · supabase/migrations/**    — scanned whole; clean today.
 *   · backend/migrations/**     — scanned whole, EXCEPT two historical files keep a
 *                                 `::geography` cast (see GRANDFATHERED below). Those
 *                                 are one-shot AREA computations run once at boundary
 *                                 load, not request-time reads, and they are already
 *                                 applied to prod and immutable. `ST_Transform` is
 *                                 forbidden everywhere, including in those two files.
 *
 * ⚠ COMMENTS ARE BLANKED BEFORE MATCHING. The pointer comments this guard is paired
 * with (essentialsService.ts, zipQueries.ts) NAME both patterns on purpose, and a
 * naive text scan would trip on its own documentation. Only real (non-comment) SQL
 * counts — which is also exactly what "a live query path" means.
 *
 * Dependency-free (node builtins only), so it lives as a step in the `static guards`
 * job with no `npm ci`. Exit 0 = clean. Exit 1 = a forbidden pattern in live SQL.
 *
 * Usage:
 *   node backend/scripts/check-postgis-spatial-ref-guard.mjs
 */

import { readdirSync, readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// This file is <repo>/backend/scripts/check-postgis-spatial-ref-guard.mjs, so the
// repo root is three levels up. Resolving from the script rather than process.cwd()
// makes the check correct whether CI runs it from the repo root or from backend/.
const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/**
 * Directories to scan, and which file extensions in each. Paths are repo-relative.
 */
const SCOPE = [
  { dir: 'backend/src', ext: '.ts' },
  { dir: 'supabase/migrations', ext: '.sql' },
  { dir: 'backend/migrations', ext: '.sql' },
];

/**
 * Generated by `supabase gen types`; the PostGIS function catalogue it emits NAMES
 * `st_transform` as a row, which is a catalogue entry, not a call site. Excluded by
 * basename at any depth (there are three: types/, trivia/types/, vq/types/).
 */
const EXCLUDE_BASENAMES = new Set(['database.types.ts']);

/**
 * The only pre-existing `::geography` casts in scope, both in immutable historical
 * migrations that compute an area ONCE at boundary-load time (not per request). They
 * predate this guard; new occurrences anywhere are still forbidden. If you are here
 * because a NEW migration needs `::geography`, that is a decision 0006 re-open — get
 * sign-off; do not add it to this list to make the guard pass.
 */
const GRANDFATHERED_GEOGRAPHY = new Set([
  'backend/migrations/1363_city_of_south_tucson.sql',
  'backend/migrations/CC_0023_monterey_park_council_district_boundaries.sql',
]);

/** `ST_Transform` in any casing. Forbidden in every scanned file, no exceptions. */
const ST_TRANSFORM = /st_transform/i;
/** A `::geography` cast, tolerating whitespace after the `::`. */
const GEOGRAPHY_CAST = /::\s*geography\b/i;

const FAIL_MESSAGE =
  'ST_Transform/::geography reads public.spatial_ref_sys, which anon can write. ' +
  'This re-opens ev-cto decision 0006 (accepted risk). Get sign-off before merging.';

/**
 * Blank every comment to spaces, preserving line breaks (so line numbers survive)
 * and offsets. Covers `/* *\/` blocks, `--` SQL line comments and `//` line
 * comments, which spans both the .sql and .ts files in scope. String and template
 * literals are left intact on purpose: a `::geography` inside a SQL template literal
 * is live code and must be caught.
 */
function blankComments(text) {
  const blank = (m) => m.replace(/[^\n]/g, ' ');
  return text
    .replace(/\/\*[\s\S]*?\*\//g, blank)
    .replace(/--[^\n]*/g, blank)
    .replace(/\/\/[^\n]*/g, blank);
}

function filesIn(relDir, ext) {
  const abs = path.join(REPO_ROOT, relDir);
  if (!existsSync(abs)) return [];
  return readdirSync(abs, { recursive: true, encoding: 'utf8' })
    .filter((f) => f.endsWith(ext))
    .filter((f) => !EXCLUDE_BASENAMES.has(path.basename(f)))
    .map((f) => path.join(relDir, f).split(path.sep).join('/'));
}

const offenders = [];

for (const { dir, ext } of SCOPE) {
  for (const rel of filesIn(dir, ext)) {
    const code = blankComments(readFileSync(path.join(REPO_ROOT, rel), 'utf8'));
    const lines = code.split('\n');
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      if (ST_TRANSFORM.test(line)) {
        offenders.push({ rel, line: i + 1, pattern: 'ST_Transform' });
      }
      if (GEOGRAPHY_CAST.test(line) && !GRANDFATHERED_GEOGRAPHY.has(rel)) {
        offenders.push({ rel, line: i + 1, pattern: '::geography cast' });
      }
    }
  }
}

if (offenders.length === 0) {
  console.log(
    'postgis spatial_ref_sys guard — no ST_Transform and no new ::geography cast in ' +
    'backend/src, supabase/migrations or backend/migrations. Decision 0006 holds.',
  );
  process.exit(0);
}

console.error(
  `postgis spatial_ref_sys guard — ${offenders.length} forbidden pattern(s) in live SQL:\n`,
);
for (const o of offenders) {
  console.error(`  · ${o.rel}:${o.line} — ${o.pattern}`);
}
console.error('');
console.error(FAIL_MESSAGE);
process.exit(1);
