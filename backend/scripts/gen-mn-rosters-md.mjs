#!/usr/bin/env node
/**
 * gen-mn-rosters-md.mjs
 *
 * Writes data/seed-mn-legislature-2026/ROSTERS.md from data/mn-legislature-roster.json, so the
 * 201-row table is machine-generated and carries no transcription risk. The prose above the
 * tables is authored; only the tables and the counts come from the roster.
 *
 *   node scripts/gen-mn-rosters-md.mjs
 */
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROSTER = path.join(HERE, '..', 'data', 'mn-legislature-roster.json');
const OUT = path.join(HERE, '..', 'data', 'seed-mn-legislature-2026', 'ROSTERS.md');

const r = JSON.parse(fs.readFileSync(ROSTER, 'utf8'));
const c = r.counts;
const REUSED = { '55B': 'Kaela Berg', '54': 'Eric Pratt' };
const created = c.seated - Object.keys(REUSED).length;

const distSort = (a, b) => {
  const na = parseInt(a.district, 10), nb = parseInt(b.district, 10);
  return na === nb ? a.district.localeCompare(b.district) : na - nb;
};

function table(chamber) {
  const rows = r.roster.filter((x) => x.chamber === chamber).sort(distSort);
  const out = ['| District | `geo_id` | Member | Disposition | Source page |', '| --- | --- | --- | --- | --- |'];
  for (const x of rows) {
    const url = x.house_profile_url || x.senate_bio_url || '';
    if (x.vacant) {
      out.push(`| **${x.district}** | \`${x.geo_id}\` | *(vacant ${x.first_vacant_day})* | 🔴 **vacant** — ${x.departed} ${x.how_ended} | [profile](https://www.house.mn.gov/members/profile/15367) |`);
      continue;
    }
    const reused = REUSED[x.district];
    const disp = reused ? '♻ **reused** existing row' : 'created';
    const alt = x.alternate_names && x.alternate_names.length ? ` <br><sub>also filed as ${x.alternate_names.join(', ')}</sub>` : '';
    out.push(`| ${x.district} | \`${x.geo_id}\` | ${x.full_name}${alt} | ${disp} | [page](${url}) |`);
  }
  return out.join('\n');
}

const md = `# Minnesota Legislature — MN-2 roster

Wave **MN-2** of the Knight Foundation cities programme, slice 5. Generated by
\`scripts/gen-mn-rosters-md.mjs\` from \`data/mn-legislature-roster.json\`; the tables below are
machine-generated, not transcribed.

**${c.offices} seats — ${c.STATE_LOWER} House + ${c.STATE_UPPER} Senate. ${created} people created, ${Object.keys(REUSED).length} reused, ${c.vacant} seat vacant.**

Slice notes: [\`.planning/knight-foundation/mn.md\`](../../../.planning/knight-foundation/mn.md).
Migrations: \`CC_0107\` (structure), \`CC_0108\` (occupancy) — both slots **reserved from the
allocator**, not counted.

## Sources

| | Source | What it is | Rows | Read |
| --- | --- | --- | --- | --- |
| **A1** | \`www.house.mn.gov/members/\` | The House's own member list. One document holding five tabs | **134** × 4 concordant tabs | 2026-09-14 |
| **A2** | \`www.senate.mn/api/members\` | The Senate's own JSON API, behind its Vue front end | **67** | 2026-09-14 |
| **B** | \`data.openstates.org/people/current/mn.csv\` | Open States — a third party, able to know about a change the chambers missed | **200** | 2026-09-14 |
| **C** | 201 individual member pages | \`house.mn.gov/members/profile/<id>\` and \`senate.mn/members/member_bio.html?mem_id=<id>\` — the change-check | **201** | 2026-09-14 |

**A and B agree on all ${c.seated} seated districts. Zero disagreements.**

Source B is a **detector, not an oracle** — but on this slice it was the only source that was
*right*, so the reverse holds too: the chambers' own lists are not oracles either.

### How the Senate API was found

\`senate.mn/members\` answers \`curl\` with **4,319 bytes of Vue shell** and no roster at all. The
endpoint is in the page's own \`memberList\` chunk: \`/js/memberList.04da8d5c.js\` declares
\`S = "/api/members"\`. This is GA-5's rule again — **when a site publishes no documented service,
ask what its own page queries.** A negative result from the HTML is a fact about the HTML.

### The agreement was controlled before it was believed

A uniform answer is a broken detector until a positive control passes. Five defects were planted
into source B and the diff re-run (\`build-mn-legislature-roster.mjs --self-test\`):

| Control | Planted | Reported | |
| --- | --- | --- | --- |
| 1 | nothing | 0 disagreements | baseline |
| 2 | SD-35 surname corrupted | 1 | ✅ |
| 3 | HD-1A row deleted | 1 | ✅ |
| 4 | HD-64A relabelled 64B | 2 | ✅ |
| 5 | Open States seats the **vacant** 21A | 1 | ✅ |

## 🔴 Source defects found

### 🔴🔴 A ROSTER LIST PAGE IS NOT A CHANGE-CHECK

\`house.mn.gov/members/\` listed **Joe Schomacker for 21A on 2026-09-14**, three months after he
left. Neither chamber publishes a vacancy marker of any kind: a \`grep\` for \`vacan\` over the House
list page and the Senate API returns **nothing**. The only in-band signal is a banner on the
member's own profile —

> **Rep. Joe Schomacker** — *Resigning effective 11:59 p.m. Sunday, June 21st 2026*

— so the change-check is all **201** individual pages, swept by \`scan-member-status.mjs\`. It reported
exactly one status note in 201, and its own positive controls (a resignation banner, a vacancy
wording, a death wording and a successor wording, each planted into a copy of SD-35) all fired.

The House's own Session Daily settles the disposition: *"No special election will be called to fill
the remainder of his term."* **21A is vacant until 2026-11-03**, first vacant day **2026-06-22**.

### 🔴 THE HOUSE'S OWN LEADERSHIP TAB IS STALE FOR TWO SEATS

The Leadership tab lists **Amanda Hemmingsen-Jaeger (47A)** and **Kaohly Vang Her (64A)**, both of
whom left in 2025 — Hemmingsen-Jaeger is now the **senator for district 47**. The Alphabetical,
District Order, Republican and DFL tabs all carry the successors, **Shelley Buck** and **Meg
Luger-Nikolai**, and Open States agrees with those four. One document, five lists, and they do not
all say the same thing. The Leadership tab is read here only to be reported.

### 🔴 EIGHT MEMBER NAMES ARE HTML-ENCODED

\`Mar&#237;a Isa P&#233;rez-Vega\` is one of them. A raw regex capture writes mojibake into a
voter-facing field. \`extract-house-tabs.mjs\` decodes, and refuses to run if it finds no encoded
name to decode — a decoder that is never exercised has proved nothing.

### ⚠ OPEN STATES IS ONE SHORT, AND IT IS THE ONE THAT IS RIGHT

Source B carries **133** House rows, not 134. The missing one is **21A** — Open States had already
dropped Schomacker. Every other seat matched.

## 🔴 Five name collisions, and they split two ways

Production holds an **active** politician row with the same \`(first_name, last_name)\` for five of
the ${c.seated} members, and \`essentials.politician_name_duplicate_guard\` refuses those inserts. Each was
**read** before it was classified — 2 of 4 name hits in the Georgia wave were a Colorado senator
and a Utah treasurer.

| Seat | Roster name | Existing row | Verdict |
| --- | --- | --- | --- |
| **55B** | Kaela Berg | Kaela Berg, candidate MN-02 (\`-270203\`) | ♻ **same person** — represents Burnsville, ran in the MN-02 DFL primary |
| **54** | Eric R. Pratt | Eric Pratt, candidate MN-02 (\`-270201\`) | ♻ **same person** — sitting senator, GOP nominee for MN-02 |
| **20B** | Steven Jacob | Steven Jacob, candidate **KS**-01 (\`-200105\`) | ✂ **different** — a Libertarian from Lawrence, Kansas |
| **9B** | Tom Murphy | Tom Murphy, **Mayor of Sahuarita, AZ** (\`-4014001\`) | ✂ **different** |
| **64** | Erin P. Murphy | Erin **J.** Murphy, **Boston City Councillor** (\`-2507000004\`) | ✂ **different** |

⚠ **The guard is lifted for three rows, not for the migration.** \`CC_0108\` inserts the ${c.seated - Object.keys(REUSED).length - 3} rows with
no namesake while the trigger is **armed**, so a collision nobody anticipated still stops the
migration; only then is \`essentials.allow_duplicate_name\` set to \`'on'\` for the three above, and
back to \`'off'\` immediately afterwards.

### 🟢 The fifth collision was invisible until a different bug was fixed

An early draft of the roster builder took \`full_name\` from the chamber and \`first_name\` from Open
States, writing **"Steven Jacob"** with \`first_name\` **"Steve"**. The guard keys on
\`(first_name, last_name)\`, so that mismatch hid the Kansas Steven Jacob from the reuse search
entirely — the exact-match query returned **four** collisions, not five. ▶ **A field pair that a
constraint reads must come from ONE source.**

## 🔴 There is no \`term_start\` to be had, and none is invented

The richest per-member pages either chamber publishes give an election **year** and an ordinal —
"Elected: 2010 / Term: 8th" (House), "re-elected 2020, 2022 / Term: 4th" (Senate). The Legislative
Reference Library's legislator database gives **biennia** ("House 1971-72"). Neither is a date.

At least six sitting members took their seats at a **2025 special election** rather than at the
start of the biennium, so the constitutional first-Monday-in-January date would be positively
wrong for them and is not a fact about anyone else either. Every term is written **open-ended at
\`start_precision = 'unknown'\`** — the GA-2 and IN-2 pattern.

\`essentials.seat_officeholder()\` is **not** used: it refuses a NULL \`term_start\` by design.

## 🔴 All 201 seats are on the 2026-11-03 ballot

Every Minnesota House seat is elected every two years, and the Senate class elected in 2022 serves
through 2026. **Re-run the change-check immediately before applying** if this slips past early
November. A certified result is not a fact about who holds the seat; only a *special*-election
winner starts early.

## House — ${c.STATE_LOWER} seats

${table('STATE_LOWER')}

## Senate — ${c.STATE_UPPER} seats

${table('STATE_UPPER')}
`;

fs.writeFileSync(OUT, md);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${c.offices} seats`);
