#!/usr/bin/env node
/**
 * check-suppressed-answer-reads — every read of a user's answers must be able
 * to hide the ones that no longer stand.
 *
 * 🔴 WHAT THIS EXISTS TO PREVENT, AND WHY A REVIEWER CANNOT.
 * CC_0061 decides whether a stored answer still means what it meant; CC_0062
 * puts that decision into `inform.compass_responses_effective`, which is
 * `compass_responses_current` minus the answers it calls `moved` or
 * `invalidated`. Eleven reads in backend/src had to switch to it.
 *
 * A twelfth read written next month, by anyone, that reaches for
 * `compass_responses_current` out of habit is not a visible mistake. It compiles,
 * it passes its tests, it returns rows, and today — while Season 1 is the open
 * season — it returns EXACTLY THE SAME ROWS, because every answer is `fresh`
 * until the changeover. The bug is dormant until a season opens and then shows
 * somebody a stance on a rung they never chose. Nothing in review catches that,
 * because at review time the two views are indistinguishable.
 *
 * So the gate is the reviewer. It is the mechanism that makes "a new read
 * inherits suppression by default" true rather than aspirational.
 *
 * ⚠ WRITES ARE NOT READS. Saving an answer still writes `compass_responses`.
 * Suppression withholds a value; it must never destroy one, and the user's
 * stored number is what the re-ask asks them to revisit.
 *
 * ⚠ IT SCANS THE BUILDER HALF TOO. Six of the eleven were PostgREST builder
 * calls — `.from('compass_responses_current')` — which name the view inside a
 * quoted argument with no clause keyword and no `inform.` prefix. A gate that
 * matched SQL text only would have reported "all clear" over half of them. This
 * is the same blind spot #349 found in check-answer-season-consumers.
 *
 * THE ESCAPE HATCH IS A STATED DECISION, not a silent pass — same shape as
 * `@season-scope` and CLAUDE.md's `@context-decision`. Some reads are honestly
 * about what the user stored rather than what still stands: an export, an admin
 * record, or the re-ask itself showing someone the answer it wants them to
 * revisit. A bare marker is refused; it must carry a reason of real length.
 *
 *   -- @suppression-scope: all-answers — the re-ask has to show the user the
 *   --   answer it is asking about, so hiding suppressed rows here would hide
 *   --   the entire point of the prompt.
 *
 * Exit 0 = clean. Exit 1 = at least one undeclared read.
 */

import { readdirSync, readFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = join(process.cwd(), 'src');

/** The view that does the season collapse but NOT the suppression. */
const TARGET = 'compass_responses_current';

/**
 * A SQL read of it. `_current` and `_effective` are distinct strings, so unlike
 * check-answer-season-consumers there is no word-boundary subtlety here — the
 * name either appears or it does not.
 *
 * Reads only: a write names `compass_responses`, the base table, which this
 * pattern cannot match.
 */
const SQL_READ = new RegExp(`(?:from|join)\\s+(?:inform\\.)?${TARGET}\\b`, 'i');

/** A PostgREST builder read — `.from('compass_responses_current')`. */
const BUILDER_READ = new RegExp(`\\.\\s*from\\s*\\(\\s*(['"\`])${TARGET}\\1`, 'gi');

const MARKER = /@suppression-scope:\s*all-answers/i;

/**
 * 'ok' | 'no-reason' | null
 *
 * ⚠ THE REASON IS CONFINED TO THE COMMENT IT IS WRITTEN IN, and that is not
 * fussiness. Reading "the rest of the text" instead let the SQL body itself
 * count as the justification, so a bare `@suppression-scope: all-answers` above
 * a long enough query scored as declared — the gate's own tests caught it. The
 * reason is the marker's own line plus any `--` / `*` / `//` continuation lines
 * directly beneath it, and nothing else.
 */
function declared(rawText) {
  const m = MARKER.exec(rawText);
  if (!m) return null;

  const lines = rawText.slice(m.index).split('\n');
  const parts = [lines[0].replace(/@suppression-scope:\s*all-answers\s*(?:—|--|-|:)?\s*/i, '')];
  for (let i = 1; i < lines.length; i++) {
    if (!/^\s*(?:--|\*|\/\/)/.test(lines[i])) break;
    parts.push(lines[i].replace(/^\s*(?:--|\*|\/\/)\s?/, ''));
  }

  const reason = parts.join(' ').trim();
  return reason.length >= 20 ? 'ok' : 'no-reason';
}

function sourceFiles(root) {
  return readdirSync(root, { recursive: true, encoding: 'utf8' })
    .filter((f) => f.endsWith('.ts'))
    .filter((f) => !f.endsWith('.test.ts'))
    // Generated by `supabase gen types`; it names every view in the schema.
    .filter((f) => f.split(sep).join('/') !== 'types/database.types.ts')
    .map((f) => join(root, f));
}

/**
 * Blank comments to spaces rather than removing them, so offsets — and so line
 * numbers — survive for the builder scan.
 */
function blankComments(text) {
  const blank = (m) => m.replace(/[^\n]/g, ' ');
  return text
    .replace(/\/\*[\s\S]*?\*\//g, blank)
    .replace(/--[^\n]*/g, blank)
    .replace(/\/\/[^\n]*/g, blank);
}

/** Every backtick literal, with the line it starts on. */
function templateLiterals(text) {
  const out = [];
  const re = /`(?:[^`\\]|\\[\s\S])*`/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    out.push({ body: m[0], line: text.slice(0, m.index).split('\n').length });
  }
  return out;
}

function scan(root) {
  const offenders = [];
  const declaredSites = [];

  for (const path of sourceFiles(root)) {
    const raw = readFileSync(path, 'utf8');
    const rel = relative(root, path).split(sep).join('/');

    // --- SQL half: one decision per literal, not per file.
    for (const { body, line } of templateLiterals(raw)) {
      const sql = blankComments(body);
      if (!SQL_READ.test(sql)) continue;

      const verdict = declared(body);
      if (verdict === 'ok') {
        declaredSites.push({ rel, line, kind: 'SQL' });
      } else if (verdict === 'no-reason') {
        offenders.push({
          rel, line, kind: 'SQL',
          why: `@suppression-scope carries no reason — state why this read must see suppressed answers (20+ chars)`,
        });
      } else {
        offenders.push({
          rel, line, kind: 'SQL',
          why: `reads ${TARGET}, which cannot hide a moved or invalidated answer`,
        });
      }
    }

    // --- Builder half: a quoted table name, so comments are blanked first and
    // the surrounding line is what carries any marker.
    const blanked = blankComments(raw);
    BUILDER_READ.lastIndex = 0;
    let b;
    while ((b = BUILDER_READ.exec(blanked)) !== null) {
      const line = blanked.slice(0, b.index).split('\n').length;
      // A builder call has no literal to hang a marker in, so the declaration is
      // read from the ten lines above it, in the raw text.
      const context = raw.split('\n').slice(Math.max(0, line - 11), line).join('\n');
      const verdict = declared(context);
      if (verdict === 'ok') {
        declaredSites.push({ rel, line, kind: 'builder' });
      } else if (verdict === 'no-reason') {
        offenders.push({
          rel, line, kind: 'builder',
          why: `@suppression-scope carries no reason — state why this read must see suppressed answers (20+ chars)`,
        });
      } else {
        offenders.push({
          rel, line, kind: 'builder',
          why: `builder read of ${TARGET}, which cannot hide a moved or invalidated answer`,
        });
      }
    }
  }

  return { offenders, declaredSites };
}

const { offenders, declaredSites } = scan(ROOT);

if (declaredSites.length > 0) {
  console.log(`suppression scope — ${declaredSites.length} site(s) declared @suppression-scope: all-answers:`);
  for (const d of declaredSites) console.log(`  · ${d.rel}:${d.line} (${d.kind})`);
  console.log('');
}

if (offenders.length === 0) {
  const files = new Set(declaredSites.map((d) => d.rel)).size;
  console.log(
    `suppressed-answer reads — every user-answer read the effective view` +
    (files ? `, with ${declaredSites.length} declared exception(s)` : '') + '.'
  );
  process.exit(0);
}

const byFile = new Map();
for (const o of offenders) {
  if (!byFile.has(o.rel)) byFile.set(o.rel, []);
  byFile.get(o.rel).push(o);
}

console.error(
  `suppressed-answer reads — ${offenders.length} site(s) in ${byFile.size} file(s) read ${TARGET}:`
);
for (const [rel, list] of byFile) {
  console.error(`  ${rel}`);
  for (const o of list) console.error(`    · ${rel}:${o.line} — ${o.why}`);
}
console.error('');
console.error(`Read inform.compass_responses_effective instead (CC_0062). It is`);
console.error(`${TARGET} minus the answers CC_0061 calls moved or`);
console.error(`invalidated, and it returns identical rows until the season changeover —`);
console.error(`which is exactly why this is invisible in review and gated here.`);
console.error('');
console.error(`If this read genuinely needs the answers that no longer stand, say so:`);
console.error(`  -- @suppression-scope: all-answers — <why, 20+ chars>`);
process.exit(1);
