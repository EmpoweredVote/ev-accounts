#!/usr/bin/env node
/**
 * gen-sc-rosters-md.mjs — Knight program, wave SC-2.
 *
 * Writes data/seed-sc-legislature-2026/ROSTERS.md from the reconciled roster JSON, the oath
 * search and the journal departure sweep. Every table below is machine-generated from those
 * files, so no seat is transcribed by hand. Touches no database.
 */
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.join(HERE, '..', 'data', 'seed-sc-legislature-2026');
const roster = JSON.parse(fs.readFileSync(path.join(HERE, '..', 'data', 'sc-legislature-roster.json'), 'utf8'));
const oaths = JSON.parse(fs.readFileSync(path.join(DATA, 'oath-dates.json'), 'utf8'));
const departures = JSON.parse(fs.readFileSync(path.join(DATA, 'departures.json'), 'utf8'));

const H = roster.chambers.house;
const S = roster.chambers.senate;
const all = [...H.members.map((m) => ({ ...m, chamber: 'House', abbr: 'HD' })), ...S.members.map((m) => ({ ...m, chamber: 'Senate', abbr: 'SD' }))];
const dated = all.filter((m) => m.term_start);

const rfaFindings = roster.findings.filter((f) => f.includes('RFA_'));
const ccOf = (c) => c.change_check ?? { tested: 0, named: 0, not_named: [], wrong_district: [], departure: [], errors: [] };

const lines = [];
const w = (s = '') => lines.push(s);

w('# South Carolina General Assembly — SC-2 roster');
w();
w('Wave **SC-2** of the Knight Foundation cities programme, slice 7. Generated by');
w('`scripts/gen-sc-rosters-md.mjs` from `data/sc-legislature-roster.json`, `oath-dates.json` and');
w('`departures.json`; every table below is machine-generated, not transcribed.');
w();
w(`**${all.length} seats — ${H.members.length} House + ${S.members.length} Senate. 0 vacancies.**`);
w();
w('Slice notes: [`.planning/knight-foundation/sc.md`](../../../.planning/knight-foundation/sc.md).');
w();
w('## Sources');
w();
w('| | Source | What it is | Rows | Read |');
w('| --- | --- | --- | --- | --- |');
w(`| **A** | \`scstatehouse.gov/member.php?chamber=H\\|S\` | each chamber's own member list, carrying the member code, name, party and district | **${H.members.length} + ${S.members.length}** | ${roster.generated_at.slice(0, 10)} |`);
w(`| **B** | \`data.openstates.org/people/current/sc.csv\` | Open States — a third party, able to know about a change source A missed | **${roster.sources.open_states.rows_house + roster.sources.open_states.rows_senate}** | ${roster.generated_at.slice(0, 10)} |`);
w('| **C** | `gis.state.sc.us/.../Boundaries_Districts/{House,Senate}_Districts` | the state\'s own GIS roster, run by the Revenue and Fiscal Affairs Office. Carries the member name **and that member\'s page URL** | 124 + 46 | 2026-09-20 |');
w('| **D** | `scstatehouse.gov/sess126_2025-2026/{hj,sj}{25,26}/*.htm` | the chambers\' own **journals** — the record of every oath and every resignation | 273 sitting days read | 2026-09-20 |');
w('| **E** | `scvotes.gov` | the State Election Commission, for a pending vacancy a chamber has not yet journaled | 1 special election | 2026-09-20 |');
w();
w(`**A and B agree on all ${all.length} seats. Zero disagreements** — neither by name nor by member code.`);
w(`**C disagrees on ${rfaFindings.length} seats**, every one of them read out below.`);
w();
w('Source B is a **detector, not an oracle**. Each disagreement is a reading queue against the');
w("member's own page, never a verdict.");
w();
w('### 🟢 C publishes an identifier, so a disagreement is not a guessing game');
w();
w("PA-2 could compare its third authority only by surname. South Carolina's RFA layer carries each");
w("district's `URL`, which holds that member's `scstatehouse.gov` code — so a disagreement is a");
w('comparison of identifiers, and a nickname or a punctuation change cannot masquerade as a');
w('turnover. The name comparison is kept as well, because a code can be right while a label is stale.');
w();
w('## 🔴 Source defects found');
w();
w('### C is stale on 7 of 170 districts, and it is stale in TWO DIFFERENT FIELDS');
w();
w('| Seat | A (the chamber) | C (RFA label) | C (RFA code resolves to) | Verdict |');
w('| --- | --- | --- | --- | --- |');
w('| HD-21 | Dianne Mitchell | Bobby J Cox | **Former** Rep. Bobby J. Cox | C stale in BOTH fields — Cox resigned, Mitchell sworn 2026-01-13 |');
w('| HD-98 | Greg Ford | Chris Murphy | **Former** Rep. Chris Murphy | C stale in BOTH fields — Ford sworn 2026-01-13 |');
w('| SD-12 | Lee Bright | Roger Allen Nutt | **Former** Sen. Roger A. Nutt | C stale in BOTH fields — Bright sworn 2026-01-13 |');
w('| HD-88 | John T. Lastinger, Jr. | John Lastinger ✅ | **Former** Rep. R. J. May III | 🔴 **label CURRENT, URL STALE** |');
w('| HD-50 | Keishan M. Scott | Keishan Scott ✅ | **Former** Rep. William W. Wheeler III | 🔴 **label CURRENT, URL STALE** |');
w('| HD-113 | Courtney S. Waters | Courtney Waters ✅ | **Former** Rep. Marvin R. Pendarvis | 🔴 **label CURRENT, URL STALE** |');
w('| HD-97 | Robby Robbins | Robby Robbins ✅ | Rep. Donald Ryan McCabe, Jr., **District 96** | 🔴 **label CURRENT, URL points at ANOTHER DISTRICT\'S member** |');
w();
w('🔴🔴 **FRESHNESS IS A PROPERTY OF A FIELD, NOT OF A ROW.** Four of these seven rows carry the');
w('**current** member\'s name beside a **stale** URL. A check that read only the name would have');
w('reported 3 disagreements; a check that read only the URL would have reported 7 and called four of');
w('them turnovers. Reading both is what separates "the label was updated and the link was not" from');
w('"this seat changed hands".');
w();
w('⚠ Every one of those stale URLs returns **HTTP 200 with a full member page** — the former');
w("member's own page. A 200 is not evidence of incumbency, and here it is not even evidence that the");
w('person still serves.');
w();
w('## The change-check');
w();
w(`All **${ccOf(H).tested + ccOf(S).tested}** member pages were read.`);
w();
w('| | Pages read | Page names the member | Page states the district | Errors |');
w('| --- | --- | --- | --- | --- |');
w(`| House | ${ccOf(H).tested} | **${ccOf(H).named}** | **${ccOf(H).tested - ccOf(H).wrong_district.length}** | ${ccOf(H).errors.length} |`);
w(`| Senate | ${ccOf(S).tested} | **${ccOf(S).named}** | **${ccOf(S).tested - ccOf(S).wrong_district.length}** | ${ccOf(S).errors.length} |`);
w();
w('🔴🔴 **AND THAT WAS NOT ENOUGH.** MN-2 taught that a roster LIST page is not a change-check and');
w("sent every later wave to the member's own page. South Carolina shows the member's own page is not");
w('one either: **SD-15 is held by a senator who has already signed his resignation**, and his page,');
w("his chamber's list, Open States and the state's GIS layer all show him with no qualification. See");
w('the pending-vacancy section below. The instruments that could see it were the **journals** and the');
w('**Election Commission**, not the roster.');
w();
w('## Arrivals — dated from the chambers\' own journals');
w();
w(`**${dated.length} of ${all.length} seats carry a term start.** Each one is the date the OATH was`);
w('administered, read out of that chamber\'s journal. The remaining');
w(`**${all.length - dated.length}** are written open-ended at \`unknown\` precision: neither chamber`);
w('publishes a service-start date, and "first elected" is not a term start.');
w();
w('🔴🔴 **THE ELECTION DATE IS NOT THE TERM START, AND HERE THE GAP REACHES SEVEN MONTHS.** HD-50\'s');
w('page says "Elected in Special Election June 3, 2025"; the House Journal administered his oath on');
w('**2026-01-13**, because the House was not sitting in between. A member-elect is not a member.');
w();
w('| Seat | Member | Page says elected | Journal says oath | Journal |');
w('| --- | --- | --- | --- | --- |');
for (const o of oaths.filter((x) => x.oath_date).sort((a, b) => (a.chamber === b.chamber ? a.district - b.district : a.chamber < b.chamber ? -1 : 1))) {
  const abbr = o.chamber === 'house' ? 'HD' : 'SD';
  w(`| ${abbr}-${o.district} | ${o.name} | ${o.elected} | **${o.oath_date}** | [journal](${o.journal_url}) |`);
}
w();
const undated = oaths.filter((x) => !x.oath_date);
for (const u of undated) {
  const abbr = u.chamber === 'house' ? 'HD' : 'SD';
  w(`⚠ **${abbr}-${u.district} ${u.name} is left UNDATED on purpose.** The page carries an arrival line`);
  w(`(elected ${u.elected}), but ${u.journals_scanned} journal days of the chamber he sits in today record no`);
  w('oath for him — because that line dates a **House** seat he held ten years before entering the');
  w('Senate. An arrival line on a member page can belong to the other chamber, and the search running');
  w('against the journal of the chamber they sit in TODAY is what exposes it rather than importing it.');
  w();
}
w('## 🔴🔴 A PENDING VACANCY THAT NO ROSTER SHOWS — SD-15');
w();
w('**Wes Climer (SD-15) signed an irrevocable resignation effective 2026-11-03**, under');
w('S.C. Code § 8-1-145, so that his successor is elected at the November general election rather than');
w('at a separate special election. He **remains the sitting senator today** and is written as such.');
w();
w('| Instrument | What it shows |');
w('| --- | --- |');
w('| the Senate\'s own list, his own page, Open States, RFA | Climer, SD-15, with no qualification |');
w('| the Senate Journal | **nothing** — his letter is dated after the last sitting day it covers |');
w('| `scvotes.gov` | **Senate District 15 Special Election — primary 2026-09-01, election 2026-11-03** |');
w();
w('▶ **No `term_end` is written.** A future `term_end` makes a seat silently self-vacate. The debt is');
w('recorded instead: **on 2026-11-03 SD-15 must be closed and its successor seated.** This is the');
w('Long Beach District 7 shape — a known handover, deliberately not written early.');
w();
w('⚠ He is also **already in production** as a candidate for U.S. House SC-5, with a headshot. That');
w('row is REUSED, not duplicated.');
w();
w('## The journal departure sweep');
w();
w(`Every sitting day of the 126th General Assembly was read — **273 days, ${departures.length} sentences**`);
w('containing a departure word, each one read. Nothing in them reports an unfilled seat: the');
w('resignations they carry (R. J. May III, HD-88, and the suspensions read in on 2026-01-13) are all');
w('seats that have since been refilled, and the rest are bill text, memorials and commission');
w('appointments.');
w();
w('⚠ **A journal sweep cannot see a resignation submitted after the last sitting day it covers.**');
w('That is exactly how SD-15 escaped it. The sweep proves no *announced* vacancy is unfilled; it');
w('cannot prove no vacancy exists.');
w();
w('## Constitutional facts, confirmed rather than inherited');
w();
w('| | |');
w('| --- | --- |');
w('| House | **124 single-member districts**, 2-year terms |');
w('| Senate | **46 single-member districts**, 4-year terms |');
w('| Both | fixed by S.C. Const. Art. III — which is why a polygon count can never date a South Carolina map |');
w();
w('No party is written on any person or office. Party lives on `races.primary_party`.');
w();
w('## Roster');
w();
w('| Seat | Member | Member code | Term start | Precision |');
w('| --- | --- | --- | --- | --- |');
for (const m of all) {
  w(`| ${m.abbr}-${m.district} | ${m.full_name} | \`${m.member_id}\` | ${m.term_start ?? '—'} | ${m.start_precision} |`);
}
w();

fs.writeFileSync(path.join(DATA, 'ROSTERS.md'), lines.join('\n'));
console.log(`wrote ${path.join(DATA, 'ROSTERS.md')} — ${all.length} seats, ${dated.length} dated`);
