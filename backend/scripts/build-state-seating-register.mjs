#!/usr/bin/env node
/**
 * Regenerate `backend/data/state-seating-2026/REGISTER.md` from production.
 *
 *   node scripts/build-state-seating-register.mjs [--write] [--json]
 *
 * Without --write it prints the table and changes nothing, so it can be run to see where the
 * pass stands without touching the file.
 *
 * Logic: scripts/lib/state-seating-register.mjs (pure, tested).
 *
 * 🔴 IT REWRITES THE TABLE AND THE TOTALS, NOT THE PROSE. The recipe and the two rulings in
 *    REGISTER.md are decisions, not measurements; they live between the markers below and this
 *    script never touches them. Regenerating the file must not quietly delete the reasoning that
 *    tells the next session how to use it.
 */
import path from 'node:path';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import pg from 'pg';
import dotenv from 'dotenv';
import { WAVE_SELECTION_SQL } from './lib/seating-wave.mjs';
import { buildRegister, registerTable } from './lib/state-seating-register.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.join(here, '..', '.env') });
dotenv.config();

const REGISTER_PATH = path.join(here, '..', 'data', 'state-seating-2026', 'REGISTER.md');

// ⚠ THE PER-BODY SLICES ARE THEIR OWN FILE, AND NOT IN data/transition-tracker/.
//
// Two reasons, and the second is the one that bites.
//
// 1. The design's §8.5 asks for "per-state slices" to replace the programme's single
//    "Wave 4 — State" row. That row is one of FIVE, it is GENERATED by
//    build-transition-dataset.mjs, and its four siblings are tiers too — Senate, House, December
//    locals, remaining locals. Splitting one tier into 69 rows inside a five-tier rollup makes
//    the file mean two different things at once, and hand-editing it would be erased by the next
//    generator run anyway.
//
// 2. 🔴 `backend/data/transition-tracker/` IS OWNED BY ANOTHER BRANCH. `feat/house-2026-results`
//    carries a copy of those CSVs that is some 380 rows ahead of master's, and the standing
//    instruction for that path is to rebuild and upload to the tracker artifact rather than
//    commit a competing copy from a second branch. Writing even a NEW file into that directory
//    is the fifth collision — two branches editing one path — which no jurisdiction claim and no
//    migration slot can see.
//
// So the slices sit beside the register they are built from: one source of truth, in a directory
// this work owns.
const SLICES_PATH = path.join(here, '..', 'data', 'state-seating-2026', 'waves-state.csv');

const BEGIN = '<!-- BEGIN GENERATED TABLE -->';
const END = '<!-- END GENERATED TABLE -->';

export const STATE_TIER = [
  'STATE_LOWER',
  'STATE_UPPER',
  'STATE_EXEC',
  'STATE_BOARD_EDUCATION',
  'STATE_BOARD',
];

export async function load(client) {
  const { rows } = await client.query(WAVE_SELECTION_SQL, [null, STATE_TIER, '2026-11-03']);
  return buildRegister(rows);
}

function render(reg) {
  const offices = reg.reduce((n, r) => n + r.offices, 0);
  const dated = reg.filter((r) => r.start_date).length;
  // ⚠ THIS TABLE IS OUTSTANDING WORK ONLY, AND THE SUMMARY SAYS SO. The selection reads
  // `essentials.office_pending_winner`, which CC_0460 already empties of any office carrying a
  // term dated on or after the election — so a body this pass has finished does not appear here
  // at all, and `status: 'done'` is unreachable from this source by construction. A seated body
  // leaves the queue rather than being ticked off in it, and the hand-written "What is already
  // done" section below the markers is what records it. Saying "69 bodies" without "still to do"
  // would read as the size of the whole pass, which is 73.
  return [
    `**${reg.length} bodies still to do · ${offices} offices · ` +
      `${dated} of the ${reg.length} carry a cited start date.** ` +
      `Measured ${new Date().toISOString().slice(0, 10)}. ` +
      `A body leaves this table when every seat in it is scheduled; see "What is already done".`,
    '',
    registerTable(reg),
  ].join('\n');
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) {
  if (!process.env.DATABASE_URL) {
    console.log('SKIPPED: DATABASE_URL is not set, so the register could not be measured.');
    process.exit(0);
  }

  const client = new pg.Client({ connectionString: process.env.DATABASE_URL });
  let reg;
  try {
    await client.connect();
    reg = await load(client);
  } finally {
    await client.end();
  }

  const body = render(reg);
  if (process.argv.includes('--json')) {
    console.log(JSON.stringify(reg, null, 2));
  } else if (process.argv.includes('--write')) {
    const existing = readFileSync(REGISTER_PATH, 'utf8');
    const before = existing.indexOf(BEGIN);
    const after = existing.indexOf(END);
    if (before === -1 || after === -1) {
      throw new Error(`${REGISTER_PATH} has no ${BEGIN} / ${END} markers; refusing to overwrite it.`);
    }
    writeFileSync(
      REGISTER_PATH,
      `${existing.slice(0, before + BEGIN.length)}\n\n${body}\n\n${existing.slice(after)}`,
    );
    console.log(`wrote ${REGISTER_PATH}`);

    const cols = [
      'rank', 'state', 'district_type', 'offices', 'winners', 'reelections',
      'winners_without_record', 'multi_winner_offices', 'flagged_vacant_offices',
      'start_date', 'status',
    ];
    const esc = (v) => {
      const s = v === null || v === undefined ? '' : String(v);
      return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
    };
    writeFileSync(
      SLICES_PATH,
      [
        cols.join(','),
        ...reg.map((r, i) => cols.map((c) => esc(c === 'rank' ? i + 1 : r[c])).join(',')),
      ].join('\n') + '\n',
    );
    console.log(`wrote ${SLICES_PATH} (${reg.length} slices)`);
  } else {
    console.log(body);
  }
}
