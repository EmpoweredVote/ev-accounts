#!/usr/bin/env node
/**
 * Generate CC_0307 — portraits for the 76 Hawaii legislators seated by CC_0306.
 *
 * EDIT THIS FILE, NEVER THE GENERATED SQL.
 *
 *   node scripts/gen-hi-legislature-headshots.mjs <roster-photos.json> > migrations/CC_0307_....sql
 *
 * 🔴 BOUND BY SEAT, NOT BY POLITICIAN UUID. Two of these people share a name with somebody
 *    else already in production — Mike Lee (the U.S. Senator for Utah) and Chris Todd (a
 *    Tennessee state representative). A name-bound UPDATE would put a Hawaii representative's
 *    face on the Utah senator. Binding through (chamber, district) -> office -> current holder
 *    cannot do that, and it also survives a re-run after the seat changes hands, because it
 *    would then fail the name assertion instead of silently repainting the wrong person.
 */
import fs from 'node:fs';

const SLOT = 'CC_0307';
const CDN =
  'https://kxsdzaojfaibhuzmclfq.supabase.co/storage/v1/object/public/politician_photos/hi-legislature-2026/';
const SENATE = 'Hawaii Senate';
const HOUSE = 'Hawaii House of Representatives';
const GOV = 'State of Hawaii';

const all = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
if (all.length !== 76) throw new Error(`expected 76 rows, got ${all.length}`);

// 🔴 SKIP THE TWO REUSED ROWS. Senate 23 (Awa) and Senate 24 (Keohokalole) were already in
// production as 2026 congressional candidates and already carry a mirrored portrait under a
// PUBLIC_DOMAIN licence. The Legislature's official photograph is press_use, so overwriting
// theirs would swap a freer licence for a narrower one on an image that already renders.
const SKIP = new Set(['S:23', 'S:24']);
const rows = all.filter((r) => !SKIP.has(`${r.ch}:${r.district}`));
if (rows.length !== 74) throw new Error(`expected 74 after the skip, got ${rows.length}`);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const out = [];
const w = (s = '') => out.push(s);

w(`-- ${SLOT}_hawaii_state_legislature_headshots.sql`);
w(`-- Portraits for 74 of the 76 Hawaii legislators seated by CC_0306.`);
w(`--`);
w(`-- GENERATED by scripts/gen-hi-legislature-headshots.mjs. Do not hand-edit.`);
w(`--`);
w(`-- ═══ ALL THREE FIELDS, AND WHY ═══`);
w(`--`);
w(`--   politicians.photo_custom_url   THE FIELD THAT RENDERS. The address-search read path`);
w(`--                                  builds its photo from COALESCE(photo_custom_url,`);
w(`--                                  photo_origin_url) and never reads politician_images.`);
w(`--   essentials.politician_images   carries photo_license, which the API returns to the`);
w(`--                                  frontend, and the grid reads images[] FIRST.`);
w(`--   politicians.photo_origin_url   provenance: the page the photograph came from.`);
w(`--`);
w(`-- ═══ 🔴 BOUND BY SEAT, NEVER BY NAME ═══`);
w(`--`);
w(`-- Production holds a DIFFERENT Mike Lee (U.S. Senator, Utah) and a DIFFERENT Chris Todd`);
w(`-- (Tennessee House District 73). A name-bound UPDATE would paint a Hawaii representative's`);
w(`-- face onto either of them. Every row below resolves through (chamber, district) -> office`);
w(`-- -> office_current_holder, and the gate asserts the resolved name matches the one this file`);
w(`-- was generated against.`);
w(`--`);
w(`-- ═══ LICENCE ═══`);
w(`--`);
w(`-- press_use for all 76: these are the Legislature's own official member photographs, served`);
w(`-- from capitol.hawaii.gov/memberfiles/repsenphotos/. Not federal works, no free licence.`);
w(`--`);
w(`-- ═══ 🔴 ALL 76 WERE LOOKED AT ═══`);
w(`--`);
w(`-- All 76 rendered to two contact sheets and inspected before this file was written, because nothing`);
w(`-- in this repo asks whether a headshot contains a face — a seal, a map, a blank or a torso`);
w(`-- all pass every automated check. On the Honolulu seed that step caught a department SEAL`);
w(`-- being imported as the Prosecuting Attorney's portrait. All 76 here are genuine, distinct`);
w(`-- individual headshots. Senate District 18 (Bass) is an outdoor photograph rather than the`);
w(`-- studio set, consistent with her appointment on 2026-08-09.`);
w(`--`);
w(`-- ⚠ Mirrored into Supabase storage, not hotlinked. The images are 13-641 KB at source and are`);
w(`--   stored as uploaded; none was upscaled.`);
w('');
w(`-- ── Pre-flight ────────────────────────────────────────────────────────────────`);
w(`DO $$`);
w(`DECLARE v_seated int; v_already int;`);
w(`BEGIN`);
w(`  SELECT count(och.politician_id) INTO v_seated`);
w(`    FROM essentials.offices o JOIN essentials.chambers c ON c.id=o.chamber_id`);
w(`    JOIN essentials.governments g ON g.id=c.government_id`);
w(`    LEFT JOIN essentials.office_current_holder och ON och.office_id=o.id`);
w(`   WHERE g.name=${q(GOV)} AND c.name IN (${q(SENATE)}, ${q(HOUSE)});`);
w(`  IF v_seated <> 76 THEN`);
w(`    RAISE EXCEPTION '${SLOT} pre-flight: expected 76 seated Hawaii legislators from CC_0306, found % — run CC_0306 first', v_seated;`);
w(`  END IF;`);
w(`  SELECT count(*) INTO v_already FROM essentials.politician_images pi`);
w(`    JOIN essentials.office_current_holder och ON och.politician_id=pi.politician_id`);
w(`    JOIN essentials.offices o ON o.id=och.office_id JOIN essentials.chambers c ON c.id=o.chamber_id`);
w(`    JOIN essentials.governments g ON g.id=c.government_id`);
w(`   WHERE g.name=${q(GOV)} AND c.name IN (${q(SENATE)}, ${q(HOUSE)}) AND pi.type='default';`);
w(`  IF v_already <> 2 THEN`);
w(`    RAISE EXCEPTION '${SLOT} pre-flight: expected exactly 2 pre-existing default image rows (Senate 23 Awa and Senate 24 Keohokalole, loaded as congressional candidates), found % — read them before overwriting', v_already;`);
w(`  END IF;`);
w(`END $$;`);
w('');
w(`CREATE TEMP TABLE hi_photos(`);
w(`  ch text NOT NULL, district int NOT NULL, who text NOT NULL, file text NOT NULL, origin text NOT NULL,`);
w(`  politician_id uuid, PRIMARY KEY (ch, district)) ON COMMIT DROP;`);
w('');
w(`INSERT INTO hi_photos(ch, district, who, file, origin) VALUES`);
w(
  rows
    .slice()
    .sort((a, b) => (a.ch === b.ch ? a.district - b.district : a.ch === 'S' ? -1 : 1))
    .map(
      (r) =>
        `  (${q(r.ch)}, ${r.district}, ${q(r.full_name)}, ${q(r.slug + '.jpg')}, ` +
        `${q('https://www.capitol.hawaii.gov/legislature/memberpage.aspx?member=' + r.member_id)})`,
    )
    .join(',\n') + ';',
);
w('');
w(`-- Resolve by SEAT.`);
w(`UPDATE hi_photos h SET politician_id = och.politician_id`);
w(`  FROM essentials.offices o`);
w(`  JOIN essentials.districts d ON d.id=o.district_id`);
w(`  JOIN essentials.chambers c ON c.id=o.chamber_id`);
w(`  JOIN essentials.governments g ON g.id=c.government_id`);
w(`  JOIN essentials.office_current_holder och ON och.office_id=o.id`);
w(` WHERE g.name=${q(GOV)}`);
w(`   AND c.name = CASE h.ch WHEN 'S' THEN ${q(SENATE)} ELSE ${q(HOUSE)} END`);
w(`   AND d.mtfcc = CASE h.ch WHEN 'S' THEN 'G5210' ELSE 'G5220' END`);
w(`   AND d.geo_id = '15' || lpad(h.district::text, 3, '0');`);
w('');
w(`-- 🔴 The seat must still hold the person this file was generated against.`);
w(`DO $$`);
w(`DECLARE v_miss int; v_wrong text;`);
w(`BEGIN`);
w(`  SELECT count(*) INTO v_miss FROM hi_photos WHERE politician_id IS NULL;`);
w(`  IF v_miss <> 0 THEN RAISE EXCEPTION '${SLOT}: % seat(s) did not resolve to a holder', v_miss; END IF;`);
w(`  SELECT string_agg(format('%s%s expected %L but holds %L', h.ch, h.district, h.who, p.full_name), '; ')`);
w(`    INTO v_wrong FROM hi_photos h JOIN essentials.politicians p ON p.id=h.politician_id`);
w(`   WHERE p.full_name <> h.who;`);
w(`  IF v_wrong IS NOT NULL THEN`);
w(`    RAISE EXCEPTION '${SLOT}: a portrait is bound to a seat whose holder has changed — %', v_wrong;`);
w(`  END IF;`);
w(`END $$;`);
w('');
w(`-- 1. The field that renders.`);
w(`UPDATE essentials.politicians p SET photo_custom_url = ${q(CDN)} || h.file`);
w(`  FROM hi_photos h WHERE p.id = h.politician_id;`);
w('');
w(`-- 2. The image row, which carries the licence to the frontend.`);
w(`INSERT INTO essentials.politician_images (politician_id, url, type, photo_license)`);
w(`SELECT h.politician_id, ${q(CDN)} || h.file, 'default', 'press_use'`);
w(`  FROM hi_photos h`);
w(` WHERE NOT EXISTS (SELECT 1 FROM essentials.politician_images pi`);
w(`                    WHERE pi.politician_id = h.politician_id AND pi.type='default');`);
w('');
w(`-- 3. Provenance. Written last, never into the render position.`);
w(`UPDATE essentials.politicians p SET photo_origin_url = h.origin`);
w(`  FROM hi_photos h WHERE p.id = h.politician_id;`);
w('');
w(`-- ── Post-verify gate ──────────────────────────────────────────────────────────`);
w(`DO $$`);
w(`DECLARE v_custom int; v_img int; v_disagree int; v_lic int; v_origin int; v_notjpg int; v_utah int;`);
w(`BEGIN`);
w(`  SELECT count(*) INTO v_custom FROM hi_photos h JOIN essentials.politicians p ON p.id=h.politician_id`);
w(`   WHERE p.photo_custom_url LIKE ${q(CDN + '%')};`);
w(`  IF v_custom <> 74 THEN RAISE EXCEPTION '${SLOT} gate: expected 74 photo_custom_url on the CDN, found %', v_custom; END IF;`);
w('');
w(`  SELECT count(*) INTO v_img FROM hi_photos h`);
w(`    JOIN essentials.politician_images pi ON pi.politician_id=h.politician_id AND pi.type='default';`);
w(`  IF v_img <> 74 THEN RAISE EXCEPTION '${SLOT} gate: expected 74 default image rows, found %', v_img; END IF;`);
w('');
w(`  -- The grid reads images[] first and the backend the scalar; disagreement shows two faces.`);
w(`  SELECT count(*) INTO v_disagree FROM hi_photos h`);
w(`    JOIN essentials.politicians p ON p.id=h.politician_id`);
w(`    JOIN essentials.politician_images pi ON pi.politician_id=h.politician_id AND pi.type='default'`);
w(`   WHERE pi.url IS DISTINCT FROM p.photo_custom_url;`);
w(`  IF v_disagree <> 0 THEN RAISE EXCEPTION '${SLOT} gate: % row(s) have images[].url disagreeing with photo_custom_url', v_disagree; END IF;`);
w('');
w(`  SELECT count(*) INTO v_lic FROM hi_photos h`);
w(`    JOIN essentials.politician_images pi ON pi.politician_id=h.politician_id AND pi.type='default'`);
w(`   WHERE pi.photo_license <> 'press_use';`);
w(`  IF v_lic <> 0 THEN RAISE EXCEPTION '${SLOT} gate: % image row(s) missing the press_use licence', v_lic; END IF;`);
w('');
w(`  SELECT count(*) INTO v_origin FROM hi_photos h JOIN essentials.politicians p ON p.id=h.politician_id`);
w(`   WHERE p.photo_origin_url = h.origin;`);
w(`  IF v_origin <> 74 THEN RAISE EXCEPTION '${SLOT} gate: expected 74 photo_origin_url, found %', v_origin; END IF;`);
w('');
w(`  SELECT count(*) INTO v_notjpg FROM hi_photos h JOIN essentials.politicians p ON p.id=h.politician_id`);
w(`   WHERE p.photo_custom_url NOT LIKE '%.jpg';`);
w(`  IF v_notjpg <> 0 THEN RAISE EXCEPTION '${SLOT} gate: % photo_custom_url value(s) are not image files', v_notjpg; END IF;`);
w('');
w(`  -- 🔴 The Utah senator and the Tennessee representative were NOT repainted.`);
w(`  SELECT count(*) INTO v_utah FROM essentials.politicians`);
w(`   WHERE external_id IN (-400077, -4720073) AND coalesce(photo_custom_url,'') LIKE ${q(CDN + '%')};`);
w(`  IF v_utah <> 0 THEN`);
w(`    RAISE EXCEPTION '${SLOT} gate: % Hawaii portrait(s) landed on the Utah Mike Lee or the Tennessee Chris Todd', v_utah;`);
w(`  END IF;`);
w('');
w(`  RAISE NOTICE '${SLOT} OK: 74 legislator portraits — scalar, image row and provenance all agree.';`);
w(`END $$;`);

process.stdout.write(out.join('\n') + '\n');
