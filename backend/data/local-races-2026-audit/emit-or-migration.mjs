#!/usr/bin/env node
// Emit CC_0423 from the committed Oregon analysis.
import fs from 'node:fs';

const [analysisPath, outPath] = process.argv.slice(2);
if (!analysisPath || !outPath) { console.error('usage: emit-or-migration.mjs <analysis.json> <out.sql>'); process.exit(2); }

const SRC_EXPORT = 'Oregon Secretary of State, 2026-11-03 General Election county results export (Multnomah and Washington)';
const SRC_RCV = 'Multnomah County Elections ranked-choice results report, rcvresults.multco.us, which names the winners';
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const slug = (s) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const a = JSON.parse(fs.readFileSync(analysisPath, 'utf8'));
const rows = [];
for (const c of a.contests) {
  for (const x of c.candidates) {
    const parts = x.who.trim().split(/\s+/);
    const first = parts[0];
    const last = parts[parts.length - 1];
    const source = c.basis === 'rcv-called' ? SRC_RCV : SRC_EXPORT;
    // 🔴 The citation names the publisher and the basis, never a number. AP's zero-vote
    //    uncontested races reached production as prose once; the rule is absolute now.
    const resultSource = x.result == null ? null
      : (c.basis === 'forced'
        ? `${SRC_EXPORT}; the ballot carried no more candidates than seats and the aggregate write-in line did not exceed the lowest named winner`
        : SRC_RCV);
    rows.push({
      raceId: c.raceId, contest: c.ours, basis: c.basis,
      full: x.who, first, last, incumbent: x.incumbent,
      result: x.result, certainty: x.result === 'won' ? 'called' : null,
      source, resultSource,
      externalId: `or-2026-11-03-${slug(c.ours)}-${slug(x.who)}`,
    });
  }
}

const ids = new Set(rows.map((r) => r.externalId));
if (ids.size !== rows.length) throw new Error('two candidacies share an external_id');

const values = rows.map((r) => `  (${[
  q(r.raceId), q(r.full), q(r.first), q(r.last), r.incumbent ? 'true' : 'false',
  q('active'), q(r.externalId), q(r.source),
  r.result ? q(r.result) : 'NULL',
  r.resultSource ? q(r.resultSource) : 'NULL',
  r.certainty ? q(r.certainty) : 'NULL',
].join(', ')})`).join(',\n');

const n = rows.length;
const won = rows.filter((r) => r.result === 'won').length;
const lost = rows.filter((r) => r.result === 'lost').length;
const none = rows.filter((r) => r.result === null).length;
const inc = rows.filter((r) => r.incumbent).length;
const byBasis = a.basisCounts;
const uncalled = a.contests.filter((c) => c.basis === 'uncalled');

const sql = `-- CC_0423: the Oregon local ballots for 2026-11-03
--
-- Generated by backend/data/local-races-2026-audit/emit-or-migration.mjs from
-- or-analysis-2026-11-14.json. Regenerate and diff rather than editing by hand.
--
-- ${n} candidacies across 26 races. Sources: the Secretary of State's per-county results exports
-- (Multnomah and Washington, pulled 2026-11-13 and committed under
-- backend/data/local-races-2026-audit/sources), and, for the ranked-choice contests, Multnomah
-- County's own published reports at rcvresults.multco.us.
--
-- 🔴 OREGON PUBLISHES NO WINNER FLAG AND NO OUTSTANDING-BALLOT COUNT, so most of these contests
--    are recorded WITHOUT a result. A state canvasses; it does not call. Three bases, and only the
--    first two can carry an outcome:
--      FORCED      ${String(byBasis.forced).padStart(2)} contests -- the ballot carried no more candidates than there were seats,
--                     so the outcome cannot depend on what is still being counted.
--      RCV-CALLED  ${String(byBasis['rcv-called']).padStart(2)} contests -- Multnomah County's ranked-choice reports NAME the winners.
--                     That is the publisher's call, not our arithmetic.
--      UNCALLED    ${String(byBasis.uncalled).padStart(2)} contests -- contested, nobody has called them, and the ballot is
--                     recorded while the outcome is not.
--
-- 🔴 "FEWER CANDIDATES THAN SEATS" IS NOT ENOUGH ON ITS OWN TO FORCE A RESULT. Oregon prints an
--    aggregate write-in line, and a write-in can win an Oregon local race -- Maine's House 24 was
--    decided by a declared write-in in the legislative wave. A contest counts as forced here only
--    if that whole line, read as if it were a single person, still loses to the lowest named
--    winner. All ${byBasis.forced} clear it, the closest being Sherwood's council.
--
-- 🔴 \`PrecinctsReporting\` READS "0/N" FOR EVERY CONTEST IN THESE FILES, IN A FILE FULL OF VOTES.
--    Oregon counts vote-by-mail ballots in batches, not by precinct, so the field that looks like
--    the completeness measure is unpopulated and is not read. A margin is not a bound, and a field
--    that says nothing is not a bound either. ▶ The counties certify within 20 days of the
--    election and the Secretary of State's results page still reads UNOFFICIAL; the ${byBasis.uncalled} uncalled
--    contests are a separate results pass after that.
--
-- 🔴🔴 THE EXPORT'S \`VoteFor\` COLUMN IS WRONG FOR THE RANKED-CHOICE CONTESTS and is not used: it
--    says 1 for Portland Councilor District 3, where the county's own report says three seats and
--    names three winners. Every ranked-choice contest in the export also carries ZERO votes for
--    every candidate, because the counts live at rcvresults.multco.us. Those zeros are written
--    nowhere.
--
-- 🔴🔴 A COUNTY EXPORT IS THAT COUNTY'S SUBTOTAL, NOT THE CONTEST'S TOTAL. The reader first asserted
--    the files would agree and the assertion fired immediately on US Senator, where Jeff Merkley
--    reads 301,848 in Multnomah and 176,244 in Washington -- two parts of one number. Taking "the
--    first file wins" would have understated every Portland-wide contest by the share of the city
--    outside Multnomah County. The reader anchors on the candidate and sums.
--
-- ⚠ WOOD VILLAGE'S TWO RACES ARE DELIBERATELY NOT SEEDED. Its ballot has "Councilor, Position 1"
--   and "Position 4"; we hold "Seat 1" and "Seat 2", and our Seat 2's holder Charlene Gothard is on
--   the ballot for the city's Position 1 -- so the two numbering schemes are not the same scheme.
--   Our Seat 1's holder John Miner was additionally made MAYOR by the council in January 2023,
--   which is the rotating-chair shape that eats a council seat. Two rows, two unknowns, and no
--   mapping that would not be a guess. They stay empty and are the subject of their own pass.
--
-- ⚠ ${inc} CANDIDATES ARE FLAGGED INCUMBENT, against the people our roster seats in each body. Three
--   matched on first-and-last only, because the ballot prints a middle name the roster does not:
--   Keith A Kudrna (Fairview Mayor), Maria Antonieta Reyes (Tualatin Position 1) and Mariana E
--   Valenzuela (Forest Grove). \`unaccent\` is not installed on prod, so accents are folded in the
--   reader -- "María Reyes" against "Maria Antonieta Reyes" would otherwise read as a challenger.
--
-- ⚠ NO POLITICIAN IS CREATED OR LINKED. politician_id stays NULL; seeding a person is a separate
--   act, and nothing here seats anybody.

BEGIN;

INSERT INTO essentials.race_candidates
  (race_id, full_name, first_name, last_name, is_incumbent, candidate_status, external_id, source,
   result, result_source, result_certainty)
VALUES
${values}
-- The unique index on external_id is PARTIAL, so the conflict target repeats its predicate.
ON CONFLICT (external_id) WHERE external_id IS NOT NULL DO NOTHING;

DO $$
DECLARE
  v_rows int; v_won int; v_lost int; v_null int; v_inc int; v_empty int; v_unflagged int; v_wv int;
BEGIN
  SELECT count(*) INTO v_rows FROM essentials.race_candidates WHERE external_id LIKE 'or-2026-11-03-%';
  IF v_rows <> ${n} THEN RAISE EXCEPTION 'CC_0423: % Oregon candidacies, expected ${n}.', v_rows; END IF;

  SELECT count(*) FILTER (WHERE result='won'), count(*) FILTER (WHERE result='lost'),
         count(*) FILTER (WHERE result IS NULL), count(*) FILTER (WHERE is_incumbent)
    INTO v_won, v_lost, v_null, v_inc
    FROM essentials.race_candidates WHERE external_id LIKE 'or-2026-11-03-%';
  IF v_won <> ${won} OR v_lost <> ${lost} OR v_null <> ${none} OR v_inc <> ${inc} THEN
    RAISE EXCEPTION 'CC_0423: won=% lost=% null=% incumbent=%, expected ${won}/${lost}/${none}/${inc}.', v_won, v_lost, v_null, v_inc;
  END IF;

  -- No citation may carry a vote count.
  IF EXISTS (SELECT 1 FROM essentials.race_candidates
              WHERE external_id LIKE 'or-2026-11-03-%' AND result_source ~ '[0-9][0-9,]* votes') THEN
    RAISE EXCEPTION 'CC_0423: a result_source carries a vote count.';
  END IF;

  -- Every Oregon race for this election must now carry a ballot, except Wood Village's two.
  SELECT count(*) INTO v_empty
    FROM essentials.races r
    JOIN essentials.elections e ON e.id = r.election_id
    JOIN essentials.offices o ON o.id = r.office_id
    JOIN essentials.districts d ON d.id = o.district_id
   WHERE e.election_date = '2026-11-03' AND lower(d.state) = 'or'
     AND NOT EXISTS (SELECT 1 FROM essentials.race_candidates rc WHERE rc.race_id = r.id);
  SELECT count(*) INTO v_wv
    FROM essentials.races r
    JOIN essentials.elections e ON e.id = r.election_id
   WHERE e.election_date = '2026-11-03' AND r.position_name LIKE 'Wood Village City Council%'
     AND NOT EXISTS (SELECT 1 FROM essentials.race_candidates rc WHERE rc.race_id = r.id);
  IF v_empty <> 2 OR v_wv <> 2 THEN
    RAISE EXCEPTION 'CC_0423: % empty Oregon races of which % are Wood Village -- expected exactly the 2 Wood Village rows.', v_empty, v_wv;
  END IF;

  -- Recording a ballot seats nobody.
  SELECT count(*) FILTER (WHERE NOT o.is_vacant) INTO v_unflagged
    FROM essentials.offices_missing_terms m JOIN essentials.offices o ON o.id = m.office_id;
  IF v_unflagged <> 238 THEN RAISE EXCEPTION 'CC_0423: drift baseline reads %, not 238.', v_unflagged; END IF;

  RAISE NOTICE 'CC_0423 OK: % Oregon candidacies across 26 races (won % / lost % / no result %), % flagged incumbent, only Wood Village left empty, drift baseline 238.',
    v_rows, v_won, v_lost, v_null, v_inc;
END $$;

COMMIT;
`;

fs.writeFileSync(outPath, sql);
console.log(`wrote ${outPath}: ${n} candidacies — won ${won}, lost ${lost}, no result ${none}, incumbent ${inc}`);
console.log(`uncalled contests (${uncalled.length}): ${uncalled.map((c) => c.ours).join('; ')}`);
