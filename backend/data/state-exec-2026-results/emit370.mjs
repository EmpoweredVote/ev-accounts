function STATUTE_WHOLE_SQL() {
  // Read back out of the loader, so the migration and the loader cannot drift apart.
  const src = fs.readFileSync('C:/ev-accounts-stateexec/backend/scripts/CC_0370-al-sboe-geofences.mjs', 'utf8');
  const m = src.match(/const WHOLE = \{([\s\S]*?)\n\};/);
  if (!m) throw new Error('cannot find the WHOLE county table in the loader');
  const WHOLE = Function(`return {${m[1]}}`)();
  const rows = Object.entries(WHOLE).flatMap(([d, cs]) => cs.map(c => `  (${q(`${c} County`)}, ${d})`));
  if (rows.length !== 62) throw new Error(`the loader's WHOLE table holds ${rows.length} counties, expected 62`);
  return rows.join(',\n') + ';';
}
