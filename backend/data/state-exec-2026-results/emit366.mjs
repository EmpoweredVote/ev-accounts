const split = n => {
  if (SPLIT[n]) return SPLIT[n];
  const i = n.lastIndexOf(' ');
  if (i < 1) throw new Error(`cannot split "${n}"`);
  return [n.slice(0, i), n.slice(i + 1)];
};
const bpSlug = n => 'https://ballotpedia.org/' + n.replace(/ /g, '_');
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const nn = v => (v === null || v === undefined ? 'NULL' : v);

const bodies = DATA.bodies;
const seats = [];
const people = new Map();
const calls = [];

for (const b of bodies) {
  if (b.seats.length !== b.officialCount) throw new Error(`${b.key}: ${b.seats.length} seats for official_count ${b.officialCount}`);
  const recorded = b.seats.filter(s => s.raceRecorded);
  b.seats.forEach((s, i) => {
    const endYear = s.termEnds ? Number(String(s.termEnds).slice(0, 4)) : null;
    if (s.termEnds && !Number.isInteger(endYear)) throw new Error(`${b.key}: bad termEnds ${s.termEnds}`);
    if (s.geometry === 'cd' && !Number.isInteger(s.cd)) throw new Error(`${b.key} ${s.title}: cd seat with no district number`);
    if (s.geometry === 'statewide' && s.cd) throw new Error(`${b.key} ${s.title}: statewide seat carries a district number`);
    if (s.raceRecorded && !s.onBallot2026) throw new Error(`${b.key} ${s.title}: a race is recorded for a seat that was not on the ballot`);
    if (endYear !== null) {
      if (s.onBallot2026 && endYear !== 2027) throw new Error(`${b.key} ${s.title}: on the ballot but the term ends ${endYear}`);
      if (!s.onBallot2026 && endYear <= 2027) throw new Error(`${b.key} ${s.title}: not on the ballot but the term ends ${endYear}`);
    }
    seats.push({
      bkey: b.key, skey: `${b.key}#${i + 1}`, title: s.title, who: s.holder,
      onBallot: !!s.onBallot2026, raceRecorded: !!s.raceRecorded, endYear,
      geometry: s.geometry, cd: s.cd ?? null,
      raceTitle: s.raceTitle || null, bpOffice: s.ballotpediaOffice || null,
    });
    const [f, l] = split(s.holder);
    if (!people.has(s.holder)) people.set(s.holder, { first: f, last: l, source: `${bpSlug(s.holder)} (Ballotpedia, read 2026-11-07); CC_0366` });
    if (!s.raceRecorded) return;
    const vb = BP.find(x => x.st === b.st && x.office === s.ballotpediaOffice);
    if (!vb) throw new Error(`no Ballotpedia votebox for ${b.key}/${s.ballotpediaOffice}`);
    if (!vb.candidates.length) throw new Error(`${b.key}/${s.ballotpediaOffice}: zero candidates`);
    const wins = vb.candidates.filter(c => c.won).length;
    if (wins !== 1) throw new Error(`${b.key}/${s.ballotpediaOffice}: ${wins} winners for a single seat`);
    for (const c of vb.candidates) {
      calls.push({ skey: `${b.key}#${i + 1}`, who: c.name, result: c.won ? 'won' : 'lost', writeIn: !!c.writeIn, incumbent: c.name === s.holder });
      const [cf, cl] = split(c.name);
      if (!people.has(c.name)) people.set(c.name, { first: cf, last: cl, source: `${bpSlug(c.name)} (Ballotpedia, read 2026-11-07); CC_0366` });
    }
  });
  const nRec = b.seats.filter(s => s.raceRecorded).length;
  if (nRec !== recorded.length) throw new Error('internal');
}

