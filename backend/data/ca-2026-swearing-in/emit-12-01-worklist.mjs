#!/usr/bin/env node
// Emit the 2026-12-01 worklist: the 52 Los Angeles County cities whose 106 officers have no
// installation date and no recorded winner.
//
// Generated rather than transcribed, because a hand-copied list of 52 cities is a list that
// drifts from the database the first time anybody seats one.
//
//   node emit-12-01-worklist.mjs > WORKLIST-2026-12-01.md
import 'dotenv/config';
import { Pool } from 'pg';

const pool = new Pool({ connectionString: process.env.DATABASE_URL });
const { rows } = await pool.query(`
  SELECT g.name AS city,
         count(*)::int AS offices,
         string_agg(DISTINCT o.title, ' · ' ORDER BY o.title) AS titles,
         sum((SELECT count(*) FROM essentials.race_candidates rc
                JOIN essentials.races r ON r.id = rc.race_id
                JOIN essentials.elections e ON e.id = r.election_id
               WHERE r.office_id = o.id AND e.election_date = '2026-11-03'))::int AS candidates,
         count(*) FILTER (WHERE EXISTS (
           SELECT 1 FROM essentials.races r
             JOIN essentials.elections e ON e.id = r.election_id
             JOIN essentials.race_candidates rc ON rc.race_id = r.id
            WHERE r.office_id = o.id AND e.election_date = '2026-11-03'
              AND rc.result IS NOT NULL))::int AS with_result
    FROM essentials.office_swearing_in si
    JOIN essentials.offices o ON o.id = si.office_id
    JOIN essentials.chambers ch ON ch.id = o.chamber_id
    JOIN essentials.governments g ON g.id = ch.government_id
   WHERE si.election_date = '2026-11-03' AND si.basis = 'estimated'
   GROUP BY g.name
   ORDER BY count(*) DESC, g.name`);
await pool.end();

const offices = rows.reduce((n, r) => n + r.offices, 0);
const cands = rows.reduce((n, r) => n + r.candidates, 0);
const withResult = rows.reduce((n, r) => n + r.with_result, 0);
const tidy = c => c.replace(/, California, US$/, '').replace(/^City of /, '');

console.log(`# 2026-12-01 worklist — ${offices} city officers, ${rows.length} cities

Generated by \`emit-12-01-worklist.mjs\`. Companion to \`RULES.md\`, which establishes why these
carry no date.

## 🔴 Two things are missing, not one, and both wait on the SAME event

Every one of these ${offices} offices is missing **an installation date** AND **a winner**:
${cands} candidacies across ${rows.length} cities, and **${withResult}** of the ${offices} offices has any result recorded.

That matters because the obvious plan — "watch 52 city websites for December agendas" — is the
wrong shape. Both gaps are downstream of a single upstream event:

| | date | what it unblocks |
| --- | --- | --- |
| LA County RR/CC certifies | **2026-11-27** (tentative) | the winners |
| 28-day canvass (E+28) | **2026-12-01** | the earliest lawful installation |
| County canvass deadline (E+30) | **2026-12-03** | the latest the county may take |

▶ **So this is ONE dated trigger and then one pass, not ${rows.length} independent watches.** Nothing
here can be finished before 2026-11-27, and almost all of it can be finished shortly after.

## ⚠ Why no date is written, and why a computed one would be wrong

\`Gov. Code § 36503\` gives these officers their seat *"from the date of the installation of
officers following adoption by the council of the official canvass"*. \`Elec. Code § 10262(b)\`
requires the council to act *"no later than the next regularly scheduled city council meeting"*
following the canvass — **or at a special meeting called for this purpose** — and \`§ 10263(b)\`
makes declaring the result and installing the officers one event.

🔴 So "the next regularly scheduled meeting" is an **upper bound that is systematically late**,
and cities do use the special-meeting route: Glendale was certified on 26 June 2026 and held a
special meeting to administer the oath. Writing ${offices} upper bounds as if they were dates would
repeat exactly the error \`RULES.md\` records — reading a search tool as an authority.

**Each city's date comes from that city's own agenda or minutes, and from nowhere else.**

## The cities

| city | officers | candidates | results in | titles |
| --- | ---: | ---: | ---: | --- |
${rows.map(r => `| ${tidy(r.city)} | ${r.offices} | ${r.candidates} | ${r.with_result} | ${r.titles} |`).join('\n')}

## ▶ The pass, when it runs

1. **After 2026-11-27**, take the county's certified results once and record winners for all
   ${offices} offices. One source, one pass. ⚠ The county publishes a canvass, not a call — read
   \`result_certainty\` conventions before writing \`won\`.
2. **Then**, per city, read the agenda or minutes of the meeting that declared the result and take
   the installation date from it. That meeting is the authority for both facts.
3. Replace each \`basis = 'estimated'\` row with the real date and its source. ⚠ Until then the
   rows are honest: they carry the statutory floor and say they are estimates.
`);
