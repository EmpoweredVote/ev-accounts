    FROM essentials.office_terms t
    JOIN essentials.offices o ON o.id = t.office_id
    JOIN essentials.chambers c ON c.id = o.chamber_id
   WHERE c.government_id = v_gov AND c.name = 'Board of County Commissioners'
     AND t.start_precision = 'month' AND extract(month FROM t.term_start) = 11;
  IF v_n <> 7 THEN RAISE EXCEPTION 'palm beach county: expected 7 month-precision November commissioner terms, got %', v_n; END IF;

  -- 🔴 2 APPOINTMENTS, AND THE RIGHT TWO. A count alone would pass if an elected
  -- officer were mislabelled, so assert the titles.
  SELECT count(*) INTO v_n
    FROM essentials.office_terms t
    JOIN essentials.offices o ON o.id = t.office_id
    JOIN essentials.chambers c ON c.id = o.chamber_id
   WHERE c.government_id = v_gov AND t.how_started = 'appointed';
  IF v_n <> 2 THEN RAISE EXCEPTION 'palm beach county: expected 2 appointed terms, got %', v_n; END IF;

  FOR v_t IN SELECT unnest(ARRAY['Clerk of the Circuit Court & Comptroller', 'Supervisor of Elections']) LOOP
