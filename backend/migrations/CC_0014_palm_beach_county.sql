    JOIN essentials.offices o ON o.id = t.office_id
    JOIN essentials.chambers c ON c.id = o.chamber_id
   WHERE c.government_id = v_gov AND (t.start_precision = 'unknown' OR t.term_start IS NULL);
  IF v_n <> 0 THEN RAISE EXCEPTION 'palm beach county: expected 0 unknown-precision or undated terms, got %', v_n; END IF;

  -- The precision histogram, per bucket. Measured from ROSTERS.md:
  -- day 2 / month 9 / year 1 / unknown 0.
  SELECT count(*) INTO v_n FROM essentials.office_terms t
    JOIN essentials.offices o ON o.id = t.office_id
    JOIN essentials.chambers c ON c.id = o.chamber_id
   WHERE c.government_id = v_gov AND t.start_precision = 'day';
  IF v_n <> 2 THEN RAISE EXCEPTION 'palm beach county: expected 2 day-precision terms, got %', v_n; END IF;

  SELECT count(*) INTO v_n FROM essentials.office_terms t
    JOIN essentials.offices o ON o.id = t.office_id
    JOIN essentials.chambers c ON c.id = o.chamber_id
   WHERE c.government_id = v_gov AND t.start_precision = 'year';
  IF v_n <> 1 THEN RAISE EXCEPTION 'palm beach county: expected 1 year-precision term(s), got %', v_n; END IF;

  -- All 7 commissioners dated at month precision, in November -- the
