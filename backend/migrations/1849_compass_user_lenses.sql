-- 1849_compass_user_lenses.sql
-- Custom (user-authored) compass lenses.
--
-- inform.compass_lenses is a CURATED EDITORIAL TABLE — Local/Federal/Judicial, seeded by
-- migration 1330, with no owner column and an auto_district_types scope that decides which
-- office auto-applies which lens. Adding a user_id to it would mean every read of the
-- editorial lenses starts filtering on ownership, and every user lens inherits an
-- auto-apply scope that makes no sense for it. So custom lenses get their own table.
--
-- SHAPE NOTES:
--
-- `key` is GLOBALLY unique, not unique-per-owner, and is generated by the client
-- (e.g. 'u_7f3a91'). That is deliberate and it is the one thing here that is hard to
-- change later: lenses are meant to become shareable, and a per-owner id would have to be
-- rewritten at the moment of sharing, invalidating every link already handed out. A
-- globally unique key from creation costs nothing now and is the difference between
-- sharing being a feature and sharing being a migration.
--
-- `topic_ids` is an ordered uuid[] rather than a child table with sort_order (the shape
-- compass_lens_topics uses). The editorial table needs a child table because its rows are
-- edited one topic at a time by hand in SQL; a user lens is only ever written whole, by
-- one owner, as one array. An array also survives a topic being retired without a FK
-- cascade silently deleting a row out of someone's saved lens — which matters, because a
-- retired topic in a lens is exactly the case the recalibration flag is meant to SURFACE,
-- not erase.
--
-- 🔴 THERE IS NO FK ON topic_ids, AND THAT IS THE POINT. See above: the lens must be able
-- to hold a topic id that is no longer promoted (or no longer live) so the read path can
-- tell the owner "this question changed, recalibrate" instead of quietly dropping it.
-- Existence is validated at write time in the route; it is not enforced forever by the DB.
--
-- The 8-topic ceiling is a PRODUCT decision, not a transport one: a radar chart with more
-- than 8 axes is unreadable. It is enforced here as well as in the route because a lens
-- that cannot be rendered is not a lens.
--
-- RLS: enabled with NO policies and NO grants, matching inform.compass_lenses and
-- compass_lens_topics. These tables are unreachable from PostgREST by design; the only
-- path in is the backend's service-role pool (lib/db.ts), where owner scoping is the
-- route's `WHERE owner_id = $1` — the same enforcement saveSelectedTopics() already uses.
-- Adding a policy here would imply an anon/authenticated grant that deliberately does not
-- exist.
--
-- Additive + idempotent (safe to re-run).

create table if not exists inform.compass_user_lenses (
  id          uuid primary key default gen_random_uuid(),
  owner_id    uuid not null references public.users(id) on delete cascade,
  key         text not null,
  name        text not null,
  topic_ids   uuid[] not null default '{}'::uuid[],
  visibility  text not null default 'private',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- Globally unique so a lens key can become a share link unchanged.
create unique index if not exists compass_user_lenses_key_uniq
  on inform.compass_user_lenses (key);

-- The owner read path: every route query is scoped by owner_id.
create index if not exists compass_user_lenses_owner_idx
  on inform.compass_user_lenses (owner_id);

do $$
begin
  -- 8 axes max — see the product note above. 0 is allowed: a lens is created before it is
  -- filled, and rejecting the empty state would force the UI to invent a placeholder topic.
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'inform.compass_user_lenses'::regclass
      and conname = 'compass_user_lenses_topic_count'
  ) then
    alter table inform.compass_user_lenses
      add constraint compass_user_lenses_topic_count
      check (coalesce(array_length(topic_ids, 1), 0) between 0 and 8);
  end if;

  -- Sharing is not built yet. 'unlisted' exists so the eventual share link has a state to
  -- move a lens INTO without a migration; nothing reads it today.
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'inform.compass_user_lenses'::regclass
      and conname = 'compass_user_lenses_visibility'
  ) then
    alter table inform.compass_user_lenses
      add constraint compass_user_lenses_visibility
      check (visibility in ('private', 'unlisted'));
  end if;

  -- A lens name is the only way an owner tells two of their lenses apart.
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'inform.compass_user_lenses'::regclass
      and conname = 'compass_user_lenses_name_nonempty'
  ) then
    alter table inform.compass_user_lenses
      add constraint compass_user_lenses_name_nonempty
      check (length(btrim(name)) > 0);
  end if;
end $$;

alter table inform.compass_user_lenses enable row level security;

comment on table inform.compass_user_lenses is
  'User-authored compass lenses. Server-only (RLS on, no policies, no grants) — reached '
  'through the backend pool with WHERE owner_id scoping, like inform.compass_lenses. '
  'topic_ids is intentionally un-FKd so a revised or retired topic surfaces as a '
  'recalibration prompt instead of vanishing from the owner''s lens.';
