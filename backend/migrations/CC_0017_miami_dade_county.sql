  SELECT count(*) INTO v_pol FROM essentials.politicians WHERE external_id IN (-1240091, -1212402, -1240092, -1240093, -1240094, -1240095, -1240096, -1240097, -1240098, -1240099, -1240100, -1240101, -1240102, -1240103, -1240105, -1240106, -1240107, -1240108, -1240109);
