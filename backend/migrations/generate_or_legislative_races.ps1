# generate_or_legislative_races.ps1
# Generates 239_or_legislative_races.sql
# 30 Senate districts x 1 election + 60 House districts x 1 election = 90 rows
#
# 🔴🔴 DO NOT RE-RUN THIS WITHOUT FIXING THE SENATE LOOP. THE LINE ABOVE IS THE BUG.
#
# Oregon elects HALF its Senate at a time. Or Const art IV s4: senators serve four years and
# "one-half, as nearly as possible, of the number of Senators shall be elected biennially". So a
# given general election has 15 senate contests, not 30 -- in 2026 districts 3, 4, 6, 7, 8, 10, 11,
# 13, 15, 16, 17, 19, 20, 24 and 26; in 2024 the other fifteen.
#
# This generator fans out one race per SEAT IN THE CHAMBER and has no notion of which seats are up.
# The House loop is right, because all 60 Oregon House seats are elected every two years. The Senate
# loop is wrong by exactly half, and the 15 races it invented sat in production from 2026-05-30
# asserting an election that never happened. CC_0419 deleted them on 2026-11-13; re-running this
# file as it stands would put them straight back, because ON CONFLICT DO NOTHING only protects the
# rows that already exist.
#
# ▶ A SEAT IS NOT A CONTEST. Before scaffolding races for any chamber, ask which seats are on that
#   ballot and take the list from the state, not from the size of the body. Staggered upper
#   chambers are the common case, not the exception.

if (-not $PSScriptRoot) {
    Write-Error "PSScriptRoot is empty — run this script with 'powershell -File generate_or_legislative_races.ps1', not dot-sourced."
    exit 1
}

$output = @()
$output += "-- Migration 239: OR 2026 Legislative Race Scaffold"
$output += "-- Generated by generate_or_legislative_races.ps1"
$output += "-- 30 Senate districts + 60 House districts = 90 rows, general election only"
$output += ""

# --- SENATE DISTRICTS (1..30) ---
for ($n = 1; $n -le 30; $n++) {
    $geo_id = "41" + ($n.ToString().PadLeft(3, '0'))  # '41001' through '41030'
    $pos = "OR State Senate District $n"

    $block = @"
DO `$`$
DECLARE
  v_general_id UUID;
BEGIN
  SELECT id INTO v_general_id FROM essentials.elections
  WHERE name = 'OR 2026 General' AND state = 'OR';

  INSERT INTO essentials.races (election_id, office_id, position_name, primary_party, seats)
  VALUES (v_general_id,
    (SELECT o.id FROM essentials.offices o
     JOIN essentials.districts d ON d.id = o.district_id
     JOIN essentials.chambers ch ON ch.id = o.chamber_id
     WHERE d.geo_id = '$geo_id' AND d.district_type = 'STATE_UPPER' AND d.state = 'or'
       AND ch.name = 'Oregon Senate' LIMIT 1),
    '$pos', NULL, 1)
  ON CONFLICT (election_id, position_name) WHERE primary_party IS NULL DO NOTHING;
END `$`$;
"@
    $output += $block
}

# --- HOUSE DISTRICTS (1..60) ---
for ($n = 1; $n -le 60; $n++) {
    $geo_id = "41" + ($n.ToString().PadLeft(3, '0'))  # '41001' through '41060'
    $pos = "OR State House District $n"

    $block = @"
DO `$`$
DECLARE
  v_general_id UUID;
BEGIN
  SELECT id INTO v_general_id FROM essentials.elections
  WHERE name = 'OR 2026 General' AND state = 'OR';

  INSERT INTO essentials.races (election_id, office_id, position_name, primary_party, seats)
  VALUES (v_general_id,
    (SELECT o.id FROM essentials.offices o
     JOIN essentials.districts d ON d.id = o.district_id
     JOIN essentials.chambers ch ON ch.id = o.chamber_id
     WHERE d.geo_id = '$geo_id' AND d.district_type = 'STATE_LOWER' AND d.state = 'or'
       AND ch.name = 'Oregon House of Representatives' LIMIT 1),
    '$pos', NULL, 1)
  ON CONFLICT (election_id, position_name) WHERE primary_party IS NULL DO NOTHING;
END `$`$;
"@
    $output += $block
}

# CRITICAL: Use UTF-8 without BOM — the PowerShell default Out-File appends a BOM
# that PostgreSQL rejects with "syntax error at or near ''"; use WriteAllLines instead.
[System.IO.File]::WriteAllLines(
  (Join-Path $PSScriptRoot '239_or_legislative_races.sql'),
  $output,
  [System.Text.UTF8Encoding]::new($false)
)
Write-Host "Generated 239_or_legislative_races.sql with $($output.Count) lines"
