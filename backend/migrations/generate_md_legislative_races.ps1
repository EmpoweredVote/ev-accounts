# --- SENATE DISTRICTS (1..47) ---
# All seats=1; geo_ids 24001..24047 (sequential, no sub-districts)
# IMPORTANT: ch.name = 'Maryland Senate' (short name in DB), NOT 'Maryland State Senate'
# The name_formal is 'Maryland State Senate' but the chambers.name used in queries is 'Maryland Senate'
# Using the wrong name results in NULL office_ids for all senate races (verified 2026-06-06)
for ($n = 1; $n -le 47; $n++) {
    $geo_id = "24" + ($n.ToString().PadLeft(3, '0'))  # '24001' through '24047'
    $pos = "MD State Senate District $n"

    $block = @"
DO `$`$
DECLARE
  v_general_id UUID;
BEGIN
  SELECT id INTO v_general_id FROM essentials.elections
  WHERE name = '2026 Maryland General Election' AND state = 'MD';

  INSERT INTO essentials.races (election_id, office_id, position_name, primary_party, seats)
  VALUES (v_general_id,
    (SELECT o.id FROM essentials.offices o
     JOIN essentials.districts d ON d.id = o.district_id
     JOIN essentials.chambers ch ON ch.id = o.chamber_id
     WHERE d.geo_id = '$geo_id' AND d.district_type = 'STATE_UPPER' AND d.state = 'md'
       AND ch.name = 'Maryland Senate' LIMIT 1),
    '$pos', NULL, 1)
  ON CONFLICT (election_id, position_name) WHERE primary_party IS NULL DO NOTHING;
END `$`$;
"@
    $output += $block
}

