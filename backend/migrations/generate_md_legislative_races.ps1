# --- TRAILING POST-VERIFICATION ---
# After migration 279 (12 statewide) + this migration (47 senate + 71 house = 118),
# total MD race rows must equal 130.
$verifyBlock = @"
DO `$`$
DECLARE
  v_count INT;
BEGIN
  SELECT COUNT(*) INTO v_count
  FROM essentials.races r
  JOIN essentials.elections e ON e.id = r.election_id
  WHERE e.state = 'MD';
  -- Expected: 12 statewide + 47 senate + 71 SLDL = 130 total
  IF v_count <> 130 THEN
    RAISE EXCEPTION 'Expected 130 MD race rows total (12 statewide + 47 senate + 71 SLDL), found %', v_count;
  END IF;
END `$`$;
"@
