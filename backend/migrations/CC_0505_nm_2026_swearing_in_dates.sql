  third_tue := jan1 + ((2 - EXTRACT(ISODOW FROM jan1)::int + 7) % 7) + 14;
  dec31     := make_date(EXTRACT(YEAR FROM DATE '2026-11-03')::int, 12, 31);
  IF jan1 <> nm_day THEN
    RAISE EXCEPTION '3a: the first day of January following 2026-11-03 computes as %, not %.',
      jan1, nm_day;
  END IF;
  -- 🔴 AND THE DAY OF THE WEEK IS ASSERTED, because it is the reason the near miss exists. A Friday
  -- January 1st is what makes "the next working day" a tempting misreading.
  IF EXTRACT(ISODOW FROM jan1)::int <> 5 THEN
    RAISE EXCEPTION '3a: 2027-01-01 computes as ISODOW %, expected 5 (Friday). The whole reason '
                    'the first Monday is this state''s dangerous near miss is that January 1st '
                    'falls on a Friday and a public holiday here.', EXTRACT(ISODOW FROM jan1)::int;
  END IF;
  -- 🟢 Art. V § 1's own cycle, checked: "those officers elected at the general election in 1990
  --    and all state executive officers elected thereafter".
  IF (EXTRACT(YEAR FROM DATE '2026-11-03')::int - 1990) % 4 <> 0 THEN
    RAISE EXCEPTION '3a: 2026 is not on Art. V § 1''s four-year cycle from 1990, so the clause does '
                    'not put these seven offices on this ballot at all.';
  END IF;
  -- 🟢 AND HB 9's, which is the arithmetic that proves the 5 + 5 partition of the Commission.
  IF (EXTRACT(YEAR FROM DATE '2026-11-03')::int - 2022) % 4 <> 0 THEN
    RAISE EXCEPTION '3a: 2026 is not on HB 9 § 3(C)''s cycle from 2022, so districts two, three, '
                    'five, six and seven were not up and this file is dating the wrong half of '
                    'the Commission.';
  END IF;
  IF (EXTRACT(YEAR FROM DATE '2026-11-03')::int - 2024) % 4 = 0 THEN
    RAISE EXCEPTION '3a: 2026 IS on HB 9 § 3(D)''s cycle from 2024, which would put districts one, '
                    'four, eight, nine and ten on this ballot too. Both halves cannot be up in '
                    'one year — the partition this file rests on is broken.';
  END IF;

  -- 3b. 🔴🔴 THE THREE WRONG DAYS COMPUTED BESIDE THE RIGHT ONE.
  IF first_mon <> nm_mon OR third_tue <> nm_tue OR dec31 <> nm_end THEN
    RAISE EXCEPTION '3b: the near-miss arithmetic is broken — first Monday %, third Tuesday %, '
                    'December 31st %. Expected %, % and %.',
      first_mon, third_tue, dec31, nm_mon, nm_tue, nm_end;
  END IF;
  IF EXTRACT(ISODOW FROM first_mon)::int <> 1 OR EXTRACT(ISODOW FROM third_tue)::int <> 2 THEN
    RAISE EXCEPTION '3b: the computed near misses are not a Monday and a Tuesday (% and %), so the '
                    'comparison below proves nothing.', first_mon, third_tue;
  END IF;
  IF jan1 IN (first_mon, third_tue, dec31) THEN
    RAISE EXCEPTION '3b: the candidate days are not distinct (% / % / % / %), so the comparison '
                    'below cannot discriminate.', jan1, first_mon, third_tue, dec31;
  END IF;
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in s JOIN cc0505_sel c ON c.office_id = s.office_id
   WHERE s.election_date = DATE '2026-11-03'
     AND s.swearing_in_date IN (first_mon, third_tue, dec31);
  IF n <> 0 THEN
    RAISE EXCEPTION '3b: % New Mexico seat(s) carry one of the three wrong days — % (the FIRST '
                    'MONDAY, 241 live rows across Arizona, Wisconsin, California and Idaho, and '
                    'the likely misreading because January 1st is a Friday and a public holiday), '
                    '% (the THIRD TUESDAY, which is NEW MEXICO''S OWN session convening day under '
                    'Art. IV § 5(A)) or % (December 31st, the day these terms END under Art. XX '
                    '§ 3(B) and HB 9 § 16(B)).', n, first_mon, third_tue, dec31;
  END IF;

  -- 3c. 🔴 AND NO NEW MEXICO OFFICE OUTSIDE THIS SELECTION WAS DATED FOR THIS ELECTION, except the
  --     four federal rows the federal programme put on 2027-01-03. ⚠ Note the near-collision: those
  --     cite Amendment XX and these cite Article XX. Different instruments, different countries.
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in s
    JOIN essentials.offices o    ON o.id = s.office_id
    JOIN essentials.districts dd ON dd.id = o.district_id
   WHERE lower(dd.state) = 'nm' AND s.election_date = DATE '2026-11-03'
     AND s.office_id NOT IN (SELECT office_id FROM cc0505_sel)
     AND NOT (dd.district_type IN ('NATIONAL_LOWER', 'NATIONAL_UPPER')
              AND s.swearing_in_date = DATE '2027-01-03'
              AND s.rule_id = 'us-const-amend-xx-1');
  IF n <> 0 THEN
    RAISE EXCEPTION '3c: % New Mexico row(s) for this election are neither one of this file''s 11 '
                    'nor one of the 4 federal rows (3 NATIONAL_LOWER + 1 NATIONAL_UPPER, '
                    '2027-01-03, us-const-amend-xx-1).', n;
  END IF;
  IF b.rows_nm <> 4 THEN
    RAISE EXCEPTION '3c: New Mexico carried % row(s) for this election before this file, expected '
                    '4 — the federal programme''s three U.S. Representatives and one Senator.',
      b.rows_nm;
  END IF;

  -- 3d. 🟢🟢 THE RULE RUN OVER NEW MEXICO'S OWN DATED TERM, WITH BOTH WRONG RULES BESIDE IT. One
  --     row against two zeros is what separates the rules; a check that only asked "does the
  --     computed day carry the recorded term?" would be satisfied by any rule that lands there.
  --     🔴 THE CONTROL REFUSES TO REPORT IF IT HAS LOST ITS FIXTURE — a control with no fixture
  --     proves nothing, and this corpus is one row deep.
  FOR ctl IN
    SELECT t.term_start, o.title, p.full_name,
           make_date(EXTRACT(YEAR FROM t.term_start)::int, 1, 1)        AS jan1_that_year,
           make_date(EXTRACT(YEAR FROM t.term_start)::int, 1, 1)
             + ((1 - EXTRACT(ISODOW FROM make_date(EXTRACT(YEAR FROM t.term_start)::int, 1, 1))::int
                 + 7) % 7)                                              AS first_monday_that_jan,
           make_date(EXTRACT(YEAR FROM t.term_start)::int, 1, 1)
             + ((2 - EXTRACT(ISODOW FROM make_date(EXTRACT(YEAR FROM t.term_start)::int, 1, 1))::int
                 + 7) % 7) + 14                                         AS third_tuesday_that_jan
      FROM essentials.office_terms t
      JOIN essentials.offices o    ON o.id = t.office_id
      JOIN essentials.districts dd ON dd.id = o.district_id
      LEFT JOIN essentials.politicians p ON p.id = t.politician_id
     WHERE lower(dd.state) = 'nm'
       AND dd.district_type IN ('STATE_EXEC', 'STATE_BOARD_EDUCATION')
       AND t.term_start IS NOT NULL AND t.start_precision = 'day'
     ORDER BY t.term_start
  LOOP
    c_rows := c_rows + 1;
    IF ctl.term_start = ctl.jan1_that_year            THEN c_rule := c_rule + 1; END IF;
    IF ctl.term_start = ctl.first_monday_that_jan     THEN c_mon  := c_mon  + 1; END IF;
    IF ctl.term_start = ctl.third_tuesday_that_jan    THEN c_tue  := c_tue  + 1; END IF;
    RAISE NOTICE '3d: % (%, %) — January 1st that year %, first Monday %, third Tuesday %; '
                 'this rule %, first-Monday rule %, third-Tuesday rule %.',
      ctl.term_start, ctl.title, coalesce(ctl.full_name, '(unnamed)'),
      ctl.jan1_that_year, ctl.first_monday_that_jan, ctl.third_tuesday_that_jan,
      CASE WHEN ctl.term_start = ctl.jan1_that_year         THEN 'PASS' ELSE 'fail' END,
      CASE WHEN ctl.term_start = ctl.first_monday_that_jan  THEN 'PASS' ELSE 'fail' END,
      CASE WHEN ctl.term_start = ctl.third_tuesday_that_jan THEN 'PASS' ELSE 'fail' END;
  END LOOP;
  IF c_rows <> 1 THEN
    RAISE EXCEPTION '3d: % dated New Mexico state-tier term(s), expected 1 — Michelle Lujan '
                    'Grisham''s Governor term beginning 2019-01-01, from the Governor''s own '
                    'office press release of that day (CA_0352). This control has lost or gained '
                    'a fixture and proves nothing until it is re-read. ⚠ A gained one is good '
                    'news: this corpus is a single point, not a cluster.', c_rows;
  END IF;
  IF c_rule <> 1 THEN
    RAISE EXCEPTION '3d: the one dated New Mexico term does not fall on January 1st of its own '
                    'year, so the only in-data evidence Art. XX § 3(A) and Art. V § 1 have inside '
                    'this repository has gone. Read it before writing this day.';
  END IF;
  IF c_mon <> 0 OR c_tue <> 0 THEN
    RAISE EXCEPTION '3d: a wrong rule now explains New Mexico''s dated term as well as the right '
                    'one — first-Monday matches %, third-Tuesday matches %, expected 0 and 0. '
                    'The control stops discriminating the moment that happens, and agreeing with '
                    'one rule is not evidence for it.', c_mon, c_tue;
  END IF;

  -- 3e. 🔴🔴 THE RESULTS GAP IS STILL EXACTLY ONE SEAT, RE-ASSERTED AFTER THE WRITE so the next
  --     reader inherits a measurement rather than re-deriving HB 9 § 3(C).
  SELECT count(*) INTO n
    FROM essentials.offices o JOIN essentials.districts dd ON dd.id = o.district_id
   WHERE lower(dd.state) = 'nm' AND dd.district_type = 'STATE_BOARD_EDUCATION'
     AND o.title IN ('Public Education Commissioner, District 2',
                     'Public Education Commissioner, District 3',
                     'Public Education Commissioner, District 5',
                     'Public Education Commissioner, District 6',
                     'Public Education Commissioner, District 7');
  IF n <> 5 THEN
    RAISE EXCEPTION '3e: % of HB 9 § 3(C)''s five 2026-cycle districts exist as office rows, '
                    'expected 5 (two, three, five, six and seven).', n;
  END IF;
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in s
    JOIN essentials.offices o ON o.id = s.office_id
   WHERE o.title = 'Public Education Commissioner, District 7'
     AND s.election_date = DATE '2026-11-03';
  IF n <> 0 THEN
    RAISE EXCEPTION '3e: Public Education Commissioner District 7 now carries % swearing-in '
                    'row(s) for this election. It has no race and no winner, so there is nothing '
                    'to seat into it — dating it would make CC_0506''s P4 look satisfied for a '
                    'seat nobody can fill.', n;
  END IF;

  -- 3f. 🔴🔴 THE LEGISLATURE IS STILL ABSENT, AND ITS DAY IS STILL THIS ONE. Re-asserted after the
  --     write, because this is the one state in the pass where the missing body would be absorbed
  --     into the day the file itself created.
  SELECT count(*) INTO n
    FROM essentials.offices o JOIN essentials.districts dd ON dd.id = o.district_id
   WHERE lower(dd.state) = 'nm' AND dd.district_type IN ('STATE_UPPER', 'STATE_LOWER');
  IF n <> 0 THEN
    RAISE EXCEPTION '3f: New Mexico now holds % legislative office row(s). All 70 House seats were '
                    'on the 2026 ballot under Art. IV § 4''s two-year term, and Art. XX § 3(A) '
                    'puts them on THIS FILE''S DAY — so they must be dated under their own '
                    'rule_id, never absorbed into these 11.', n;
  END IF;

  -- 4. 🔴 THE 2027-01-01 DELTA, NAMED. New Mexico is the second state on this day.
  SELECT count(*) INTO n FROM essentials.office_swearing_in WHERE swearing_in_date = nm_day;
  IF n <> b.rows_jan1 + 11 THEN
    RAISE EXCEPTION '4: rows on % went % -> %, a delta of %, expected 11.',
      nm_day, b.rows_jan1, n, n - b.rows_jan1;
  END IF;
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in s
    JOIN essentials.offices o    ON o.id = s.office_id
    JOIN essentials.districts dd ON dd.id = o.district_id
   WHERE s.swearing_in_date = nm_day
     AND s.rule_id NOT IN ('ut-const-art6-first-day-january',
                           'nm-const-art5-1-first-day-of-january',
                           'nm-22-3b-3-january-1-next-succeeding');
  IF n <> 0 THEN
    RAISE EXCEPTION '4: % row(s) on % belong to a rule this file does not know. A date shared by '
                    'two states is a coincidence of calendars, never a shared rule — name the new '
                    'one before absorbing it.', n, nm_day;
  END IF;
  -- 4b. ⚠ AND UTAH'S 50 DID NOT MOVE. The delta above would read the same if this file had written
  --     11 rows and deleted none, or if Utah had lost rows and this file had written more.
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in
   WHERE swearing_in_date = nm_day AND rule_id = 'ut-const-art6-first-day-january';
  IF n <> 50 THEN
    RAISE EXCEPTION '4b: Utah now has % rows on %, expected 50. This file must not have touched '
                    'them.', n, nm_day;
  END IF;
  -- 4c. 🔴 AND THE FIRST MONDAY DID NOT MOVE EITHER — the near miss is a live day in four states.
  SELECT count(*) INTO n FROM essentials.office_swearing_in WHERE swearing_in_date = nm_mon;
  IF n <> b.rows_jan4 THEN
    RAISE EXCEPTION '4c: rows on % (the FIRST MONDAY) went % -> %. This file must not have touched '
                    'that day — it belongs to Arizona, Wisconsin, California and Idaho.',
      nm_mon, b.rows_jan4, n;
  END IF;

  -- 5. New Mexico rows for this election moved by exactly 11.
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in s
    JOIN essentials.offices o    ON o.id = s.office_id
    JOIN essentials.districts dd ON dd.id = o.district_id
   WHERE lower(dd.state) = 'nm' AND s.election_date = DATE '2026-11-03';
  IF n <> b.rows_nm + 11 THEN
    RAISE EXCEPTION '5: New Mexico rows for this election went % -> %, a delta of %, expected 11.',
      b.rows_nm, n, n - b.rows_nm;
  END IF;

  -- 6. Repo-wide, exactly 11 rows were added — no other state was swept in.
  SELECT count(*) INTO n FROM essentials.office_swearing_in;
  IF n <> b.rows_all + 11 THEN
    RAISE EXCEPTION '6: office_swearing_in went % -> %, a delta of %, expected 11.',
      b.rows_all, n, n - b.rows_all;
  END IF;

  -- 7. 🔴 EACH GROUP READS BACK UNDER ITS OWN RULE AND ITS OWN AUTHORITY. Two instruments mean two
  --    rule_ids, counted separately — a single shared one would make the Commission's statutory
  --    basis unreadable from the data. ⚠ AND THE AUTHORITY TEXT IS ASSERTED, NOT JUST THE DATE: a
  --    citation can be right about the day and wrong about the law, and no count can see it
  --    (CC_0487's three citations, CC_0499's § 1 against § 3).
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in s
    JOIN cc0505_sel c ON c.office_id = s.office_id
   WHERE s.election_date = DATE '2026-11-03' AND c.grp = 'exec'
     AND s.basis = 'statute'
     AND s.rule_id = 'nm-const-art5-1-first-day-of-january'
     AND s.authority LIKE 'N.M. Const. Art. V, § 1 %';
  IF n <> 7 THEN
    RAISE EXCEPTION '7: % of 7 executive rows read back with basis statute under '
                    'nm-const-art5-1-first-day-of-january citing Art. V, § 1.', n;
  END IF;
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in s JOIN cc0505_sel c ON c.office_id = s.office_id
   WHERE s.election_date = DATE '2026-11-03' AND c.grp = 'pec'
     AND s.basis = 'statute'
     AND s.rule_id = 'nm-22-3b-3-january-1-next-succeeding'
     AND s.authority LIKE 'Laws 2021 (2nd Special Session), Chapter 3 (House Bill 9)%';
  IF n <> 4 THEN
    RAISE EXCEPTION '7: % of 4 Commission rows read back with basis statute under '
                    'nm-22-3b-3-january-1-next-succeeding citing HB 9 § 3.', n;
  END IF;
  -- 7b. 🔴🔴 AND EVERY ROW NAMES ART. XX § 3, THE GENERAL CLAUSE THAT DISCHARGES ART. V § 1's
  --     CARVE-OUT AND REACHES BOTH BODIES. It is the thing the ledger did not have, so a later
  --     reader must not be able to lose it: a file that cited only the two specific instruments
  --     would look identical in every count.
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in s JOIN cc0505_sel c ON c.office_id = s.office_id
   WHERE s.election_date = DATE '2026-11-03' AND s.authority LIKE '%Art. XX § 3(A)%';
  IF n <> 11 THEN
    RAISE EXCEPTION '7b: % of 11 rows cite Art. XX § 3(A). That clause — "the term of office of '
                    'every state, county or district officer … shall commence on the first day of '
                    'January next after the officer''s election" — is what closes Art. V § 1''s '
                    '"unless otherwise provided in the constitution of New Mexico", and it is the '
                    'only instrument that reaches BOTH bodies.', n;
  END IF;
  -- 7c. ⚠ AND NO ROW IS DATED ON A CLAUSE FOR A BODY IT DOES NOT BELONG TO. Art. IV §§ 4 and 5 are
  --     quoted in the notes as WARNINGS about the legislature; neither may be a citation.
  SELECT count(*) INTO n
    FROM essentials.office_swearing_in s JOIN cc0505_sel c ON c.office_id = s.office_id
   WHERE s.election_date = DATE '2026-11-03'
     AND (s.authority LIKE 'N.M. Const. Art. IV%' OR s.authority LIKE 'N.M. Const. Art. XXII%');
  IF n <> 0 THEN
    RAISE EXCEPTION '7c: % row(s) are dated ON Art. IV or Art. XXII. Art. IV § 4 is the '
                    'LEGISLATURE''s term and § 5 its session; Art. XXII § 22 is the 1912 Schedule '
                    'clause that says terms commence ON QUALIFICATION and is dead. None of them '
                    'dates any of these eleven offices.', n;
  END IF;

  -- 8. No term was written. CC_0506 seats.
  SELECT count(*) INTO n FROM essentials.office_terms t
    JOIN cc0505_sel c ON c.office_id = t.office_id
   WHERE t.term_start = nm_day;
  IF n <> 0 THEN
    RAISE EXCEPTION '8: % term(s) were written. This file records dates and seats nobody.', n;
  END IF;

  RAISE NOTICE 'CC_0505 OK: 11 New Mexico offices dated % — THE FIRST DAY OF JANUARY, from THREE '
               'instruments that agree. Art. V § 1 names the seven executives one by one and '
               'states its cycle (2026 − 1990 = 36, divisible by four); HB 9 § 3(B) dates the four '
               'Public Education Commissioners in nearly the same words, with § 16(B) saying it '
               'again from the other end of the calendar; and 🔴🔴 Art. XX § 3(A) — WHICH THE '
               'LEDGER DID NOT HAVE — commences "every state, county or district officer" on the '
               'same day and is what DISCHARGES Art. V § 1''s "unless otherwise provided in the '
               'constitution of New Mexico". That carve-out was closed by a sweep of all 24 '
               'articles and 270 sections with a pre-set positive control, not by an argument: '
               'four candidates existed, three are dead (the oath binds "before entering upon his '
               'duties"; Art. XX § 2 is a HOLDOVER clause; Art. XXII § 22 says the opposite in '
               'words and is the 1912 Schedule) and the fourth agrees. The day was COMPUTED, and '
               'all three wrong days computed beside it — % (the FIRST MONDAY, 241 live rows in '
               'four states, and the likely misreading because January 1st 2027 is a FRIDAY and a '
               'public holiday), % (the THIRD TUESDAY, NEW MEXICO''S OWN session convening day) '
               'and % (December 31st, the day these terms END). 🟢 The rule was run over New '
               'Mexico''s one dated term — Michelle Lujan Grisham''s 2019-01-01, written from a '
               'press release and not from any clause here — and it matches January 1st while '
               'BOTH wrong rules match zero. New Mexico is the SECOND state on this day; Utah''s '
               '50 rows were already here. 🔴🔴 AND TWO GAPS ARE PINNED RATHER THAN TIDIED: Public '
               'Education Commission District 7 was on this ballot under HB 9 § 3(C) and we hold '
               'NO RACE ROW FOR IT, so Patricia Gipson keeps a seat she lost; and New Mexico''s '
               '70 House seats do not exist in our data at all and take THIS FILE''S DAY under '
               'Art. XX § 3(A), so they must never be absorbed into it.',
    nm_day, nm_mon, nm_tue, nm_end;
END $$;

