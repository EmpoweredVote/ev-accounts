-- Migration 178: meetings.council_file_details — enriched bill metadata
--
-- Purpose: Store enriched metadata for LA City Council files (bills), scraped
-- from the City Clerk's CFMS system (cityclerk.lacity.org/lacityclerkconnect).
-- Each row corresponds to one council file number (e.g., "22-0158", "21-0042-S3").
--
-- Primary data source: cityclerk.lacity.org CFMS (viewrecord page)
-- Secondary sources: lacity.granicus.com RSS feed (video clip IDs),
--                    Anthropic claude-haiku-4-5 (plain-English AI summaries).
--
-- Relationship to meetings.la_council_votes:
--   la_council_votes.council_file_number is a soft reference to this table's PK.
--   No FK constraint is enforced because some vote rows have NULL council_file_number
--   (agenda items with no associated bill). The relationship is: one council_file_details
--   row → many la_council_votes rows (one per council member × vote event).

CREATE TABLE IF NOT EXISTS meetings.council_file_details (
  -- Natural primary key: the council file number as assigned by the City Clerk.
  -- Format examples: "22-0158", "21-0042-S3", "23-1022-S18"
  -- Suffixes (S3, A2, T1, etc.) are part of the key — do NOT strip them.
  council_file_number TEXT PRIMARY KEY,

  -- Bill title as scraped from CFMS "Title" field. Nullable — CFMS may return
  -- a 200 response with empty data for very new or archived filings.
  title TEXT,

  -- Mover(s): council member(s) who moved the item. PostgreSQL array because
  -- co-movers appear as multiple names (e.g., {'MIKE BONIN','NITHYA RAMAN'}).
  movers TEXT[],

  -- Seconder: council member who seconded the motion.
  second TEXT,

  -- Date the council file was introduced/received by the City Clerk.
  introduced_date DATE,

  -- Date the council file was last modified in CFMS.
  last_changed_date DATE,

  -- Array of PDF document URLs from cityclerk.lacity.org/onlinedocs/*.pdf
  -- Multiple documents (motions, staff reports, adopted files) are common.
  pdf_links TEXT[],

  -- Canonical CFMS page URL for this council file.
  -- Format: https://cityclerk.lacity.org/lacityclerkconnect/index.cfm?fa=ccfi.viewrecord&cfnumber={cfn}
  cfms_url TEXT,

  -- Granicus video clip ID for the meeting where this item was heard.
  -- Nullable — some meeting dates have no recorded clip.
  -- Construct video URL at API layer: https://lacity.granicus.com/MediaPlayer.php?view_id=129&clip_id={id}
  granicus_clip_id INTEGER,

  -- Plain-English 2-sentence summary generated by Anthropic claude-haiku-4-5.
  -- NULL for commendations, certificates, congratulatory resolutions, and
  -- recognitions (no substantive policy content to summarize).
  ai_summary TEXT,

  -- Timestamp set on every enrichment attempt, including failed scrapes.
  -- Used to determine whether a row needs re-enrichment. Always updated.
  enriched_at TIMESTAMPTZ DEFAULT now(),

  -- Timestamp set only when ai_summary was successfully generated (not NULL).
  -- Separate from enriched_at so we can distinguish "enriched but no summary"
  -- (commendation skip) from "enriched and summarized" (policy bill).
  ai_summary_at TIMESTAMPTZ
);

-- Index for lookups by introduced_date (used in Granicus clip_id matching
-- and future date-range queries).
CREATE INDEX IF NOT EXISTS council_file_details_introduced_date_idx
  ON meetings.council_file_details(introduced_date);

-- Index to find rows needing re-enrichment (enriched_at IS NULL or old).
CREATE INDEX IF NOT EXISTS council_file_details_enriched_at_idx
  ON meetings.council_file_details(enriched_at);
