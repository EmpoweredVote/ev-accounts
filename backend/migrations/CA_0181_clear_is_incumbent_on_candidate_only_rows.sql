CREATE TEMP TABLE _before ON COMMIT DROP AS
SELECT (SELECT count(*) FROM essentials.politicians p WHERE p.is_active AND p.is_incumbent) AS active_incumbents,
       (SELECT count(*) FROM essentials.politicians p WHERE p.is_active AND p.is_incumbent
          AND NOT EXISTS (SELECT 1 FROM essentials.office_terms t WHERE t.politician_id = p.id)) AS seatless_incumbents,
       (SELECT count(*) FROM _cand x JOIN essentials.politicians p ON p.id = x.id WHERE p.is_incumbent) AS to_clear;

-- ─── Pre-flight ──────────────────────────────────────────────────────────────────────────────────
DO $$
DECLARE v_n int;
BEGIN
  SELECT count(*) INTO v_n FROM _cand;
  IF v_n <> 1284 THEN RAISE EXCEPTION 'PRE: _cand holds %, expected 1284', v_n; END IF;

  -- each row is still an active, seatless candidate whose every race row says not incumbent, and is either still
  -- flagged incumbent or already cleared by this file
  SELECT count(*) INTO v_n FROM _cand x JOIN essentials.politicians p ON p.id = x.id
   WHERE p.is_active
     AND NOT EXISTS (SELECT 1 FROM essentials.office_terms t WHERE t.politician_id = p.id)
     AND EXISTS (SELECT 1 FROM essentials.race_candidates rc WHERE rc.politician_id = p.id)
     AND NOT EXISTS (SELECT 1 FROM essentials.race_candidates rc WHERE rc.politician_id = p.id AND rc.is_incumbent)
     AND (p.is_incumbent
          OR 'CA_0181 (2026-09-23): is_incumbent cleared -- the row holds no seat (no office_terms row) and every race_candidates row for it says is_incumbent = false.' = ANY (p.notes));
  IF v_n <> 1284 THEN RAISE EXCEPTION 'PRE: % of 1284 rows are still active seatless candidate-only rows', v_n; END IF;
END $$;

-- ─── 1. Clear the flag ──────────────────────────────────────────────────────────────────────────
UPDATE essentials.politicians p
   SET is_incumbent = false,
       notes = COALESCE(p.notes, ARRAY[]::text[])
               || 'CA_0181 (2026-09-23): is_incumbent cleared -- the row holds no seat (no office_terms row) and every race_candidates row for it says is_incumbent = false.'::text
  FROM _cand x
 WHERE p.id = x.id AND p.is_incumbent;

-- ─── Post-verify gate ────────────────────────────────────────────────────────────────────────────
DO $$
DECLARE v_n int; b record;
BEGIN
  SELECT * INTO b FROM _before;

  SELECT count(*) INTO v_n FROM _cand x JOIN essentials.politicians p ON p.id = x.id
   WHERE p.is_active AND NOT p.is_incumbent
     AND 'CA_0181 (2026-09-23): is_incumbent cleared -- the row holds no seat (no office_terms row) and every race_candidates row for it says is_incumbent = false.' = ANY (p.notes);
  IF v_n <> 1284 THEN RAISE EXCEPTION 'POST: % of 1284 rows cleared with the note', v_n; END IF;

  SELECT count(*) INTO v_n FROM essentials.politicians p
   WHERE 'CA_0181 (2026-09-23): is_incumbent cleared -- the row holds no seat (no office_terms row) and every race_candidates row for it says is_incumbent = false.' = ANY (p.notes)
     AND p.id NOT IN (SELECT id FROM _cand);
  IF v_n <> 0 THEN RAISE EXCEPTION 'POST: % row(s) outside _cand carry the note', v_n; END IF;

  -- exactly the rows cleared left the incumbent counts; nothing else moved
  SELECT count(*) INTO v_n FROM essentials.politicians p WHERE p.is_active AND p.is_incumbent;
  IF v_n <> b.active_incumbents - b.to_clear THEN
    RAISE EXCEPTION 'POST: % active incumbents, expected % - %', v_n, b.active_incumbents, b.to_clear;
  END IF;
  SELECT count(*) INTO v_n FROM essentials.politicians p WHERE p.is_active AND p.is_incumbent
     AND NOT EXISTS (SELECT 1 FROM essentials.office_terms t WHERE t.politician_id = p.id);
  IF v_n <> b.seatless_incumbents - b.to_clear THEN
    RAISE EXCEPTION 'POST: % seatless active incumbents, expected % - %', v_n, b.seatless_incumbents, b.to_clear;
  END IF;

  RAISE NOTICE 'CA_0181 applied: is_incumbent cleared on % candidate-only rows (1284 reviewed)', b.to_clear;
END $$;

