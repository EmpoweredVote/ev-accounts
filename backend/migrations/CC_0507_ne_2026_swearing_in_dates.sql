-- **Neb. Const. Art. XVII-5** — *Terms of office of all elected officers*:
--
--     "UNLESS OTHERWISE PROVIDED BY THIS CONSTITUTION OR BY LAW the terms of all elected officers
--      shall begin on the FIRST THURSDAY AFTER THE FIRST TUESDAY IN JANUARY next succeeding their
--      election."
--
-- 🔴 **A RESIDUAL MUST BE QUOTED WITH ITS OWN FIRST SIX WORDS ATTACHED**, or the next reader
--   applies it to a body that is carved out of it. Nebraska has such a body — see the Legislature
--   below — so this is not a hypothetical in this state.
--
-- ⚠ **Its own annotation narrows it usefully**: *"This section has reference only to officers who
--   have a fixed term."* (`Baker v. Moorhead`, 103 Neb. 811 (1919)). All thirteen have a fixed term
--   — four years for the executives and the Board of Education, six for the Commission and the
--   Regents — so all thirteen are inside it.
--
-- 🟢 **`§ 32-572(1)` IS THE LOCK, BECAUSE IT SAYS OUT LOUD THAT THE DAY LIVES SOMEWHERE ELSE:**
--   *"Every officer elected or appointed for a fixed term shall hold office until his or her
--   successor is elected or appointed and is qualified. The fixed term shall end and the successor
--   … shall qualify ON THE DAY FOR TAKING OFFICE AS PROVIDED BY LAW."* The Legislature wrote "the
--   day for taking office as provided by law" and provided it in none of the body sections.
--   Art. XVII-5 is what it points at.
