-- Term start or oath? — **TERM START**
-- ─────────────────────────────────────────────────────────────────────────────────────────────
--
-- Art. XVII-5 says the **terms** "shall begin" on the computed day and does not mention an oath.
-- ⚠ `§ 32-572(1)` does use the word *qualify* — the successor *"shall qualify on the day for taking
-- office as provided by law"* — but it fixes qualification **to** that day rather than making the
-- term begin whenever qualification happens. 🔴 **That is the opposite direction from Nevada**,
-- where `NRS 282.010(4)` starts the term *at* qualification and the day is unknowable in advance.
-- **Read the direction of the sentence.** `Art. XV-1`'s oath is a condition on entering upon duties,
-- which is Idaho's and New Mexico's shape.
--
