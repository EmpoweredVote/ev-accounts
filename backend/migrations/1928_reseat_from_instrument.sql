-- Migration 1928 — the re-read of the 165. Re-seat 34; leave 131 blank.
--
-- WHAT THIS IS. Migration 1926 blanked 165 Season 2 chairs whose own reasoning said the cited
-- instrument "does not by itself separate the rungs WITHIN that side". It kept every roll call and
-- the original reasoning verbatim, and said the rows were candidates for re-seating rather than
-- write-offs. This is that re-read.
--
-- ⚖⚖ THE UNIT OF WORK IS NOT 165 ROWS. The instruments repeat: 165 rows reduce to 59 distinct
-- (topic, instrument-set) pairs, and each was judged ONCE against the Season 2 ladder. That is why
-- a re-read is tractable where a row-by-row re-research would not be.
--
-- 🔑 THE TEST APPLIED, and it is the only one that can rescue a direction-only row:
--    DOES THE INSTRUMENT'S CONTENT STATE THE RUNG'S OWN DISTINGUISHING CLAUSE?
-- Not "which rung is nearest", not "which is least extreme" — that is a tiebreaker and a tiebreaker
-- is the signal a row is NOT evidenced. The 34 rows below pass because the rung text and the
-- instrument say the same thing. The other 131 do not, and they stay blank.
--
-- ⚠ THE TEST IS STRICTER THAN IT LOOKS, AND IT REFUSED SOME TEMPTING ROWS:
--  · 14 HEALTHCARE rows filed Medicaid-expansion bills. Rung 3 reads "expand programs for seniors
--    and low-income residents, WHILE KEEPING PRIVATE INSURANCE FOR EVERYONE ELSE". The bill expands
--    the programme; it does NOT assert the ceiling. A legislator who wants rung 1 or 2 files the
--    same bill in Texas, because it is the achievable step. Expansion proves a floor, never a
--    ceiling. BLANK. (The one row filing a constitutional amendment to PROHIBIT expansion is
--    re-seated, because a prohibition does assert a ceiling.)
--  · 31 CIVIL RIGHTS rows. A vote against repealing DEI offices is equally consistent with rungs
--    1, 2 and 3 — anyone holding any of them votes that way. It excludes the anti side and chooses
--    nothing. BLANK. ⚠ And rung 4 names FEDERAL enforcement, which a state legislator cannot
--    reach, so the anti side of this ladder is short a rung for these members.
--  · 11 ABORTION rows. Texas's trigger ban (HB1280) permits abortion only to save the mother's
--    life — rung 4 names "rape, incest, or serious threats to the mother's life" and rung 5 is
--    "no exceptions". The instrument falls BETWEEN the two rungs. BLANK, and recorded as a
--    ladder-reachability finding.
--  · 13 CLIMATE and 11 FOSSIL FUEL rows. Barring state investment in firms that boycott energy
--    companies, and prohibiting a carbon tax, are neither "ending clean energy subsidies and
--    mandates" (rung 5) nor "expanding drilling permits" (rung 4). Off axis. BLANK.
--  · 1 REDISTRICTING row authored HB 312 (86R), a redistricting commission bill — the one row that
--    could have reached rung 1 or 2. FETCHED: the bill sets eligibility by reference to a proposed
--    Section 28a, Article III, which lives in a companion constitutional amendment and NOT in this
--    instrument. Rung 1 ("no elected officials at any level") versus rung 2 ("equal representation
--    from both major parties") turns on exactly that text. BLANK, for want of the composition.
--  · 1 REDISTRICTING row is nothing but "absent, undisclaimed, on 7 of 7 quorum rolls". An absence
--    is not a position. BLANK.
--
-- ─────────────────────────────────────────────────────────────────────────────
-- THE 34 RE-SEATS, and why the instrument IS the rung in each case.
-- ─────────────────────────────────────────────────────────────────────────────
-- VOTING RIGHTS -> 4   (5 rows).  Rung 4: "Require photo ID in person AND AN ID NUMBER ON EVERY
--   MAIL BALLOT." The instrument is a vote FOR 87(2) SB1, described in the row itself as the bill
--   "which requires an ID number on every mail ballot". The rung's distinguishing clause is the
--   bill's mechanism, word for word. Rung 5 (documentary proof of citizenship to register) is not
--   in SB1.
-- REDISTRICTING -> 5   (14 rows). Rung 5: "the party that controls the state legislature WITHOUT
--   OUTSIDE INTERFERENCE." The instrument is a vote FOR the 2025 MID-DECADE congressional map drawn
--   by the legislative majority — a redraw outside the decennial cycle, by the controlling party,
--   with no commission or court mandate. Rung 4 asserts court oversight TO PREVENT EXTREME PARTISAN
--   BIAS, which a vote for that map is not.
-- SAME-SEX MARRIAGE -> 3  (5 rows). Rung 3: "Allow same-sex marriage, but PROTECT RELIGIOUS
--   ORGANIZATIONS' RIGHT TO DECLINE TO PERFORM OR HOST THESE MARRIAGES." Every instrument here is a
--   bill doing precisely that — 84(R) HB 3567 on "a marriage that violates a sincerely held
--   religious belief", 85(R) HB 1923, 86(R) HB 2109 on "the right of recusal from the performance
--   of certain marriage ceremonies". Rung 2 is excluded by the carve-out; rung 4 (civil unions
--   only) and rung 5 (ban) are different instruments nobody here filed.
--   ⚠ RESERVATION STATED, NOT HIDDEN: filing an exemption bill shows the exemption position, and
--   does not by itself prove the author would vote to keep marriage legal. Rung 3 is the only rung
--   of the five whose text the instrument states, which is the test; a reader who disagrees should
--   blank the row rather than move it.
-- RELIGIOUS FREEDOM -> 4  (6 rows). Rung 4: "allow FAITH-BASED EXEMPTIONS FROM LAWS THAT CONFLICT
--   WITH SINCERE RELIGIOUS BELIEFS." The phrase is in the instruments' own captions — "a marriage
--   that violates a sincerely held religious belief" (HB 3567), "protecting freedom of conscience
--   from government discrimination" (HB 2779, HB 1035), the protection of religious organisations
--   (HB 3172 / SB 1978) and the bar on closing places of worship (HB 1239). Rung 5 requires
--   "COMPLETE AUTONOMY IN THEIR OPERATIONS AND HIRING PRACTICES", which none of these grants.
-- SCHOOL VOUCHERS -> 2  (3 rows). Rung 2: "Opposing voucher programs and BLOCKING THEIR EXPANSION,
--   WITHOUT MOVING TO ELIMINATE EXISTING ONES." The instrument is a vote AGAINST 89(R) SB2, the
--   bill CREATING the education savings account programme. Texas had no such programme to
--   eliminate, so a vote against its creation is a block and cannot be rung 1's elimination.
-- HEALTHCARE -> 4  (1 row). Rung 4: "ONLY HELP THE POOREST PEOPLE afford healthcare and leave
--   everyone else to employers and private insurance." The instrument is 87(R) HJR 130, authored:
--   a constitutional amendment PROHIBITING the state from expanding Medicaid eligibility. A
--   constitutional bar on expansion asserts the ceiling rung 4 names. Rung 5 ("stay out of
--   healthcare entirely") is excluded: the amendment preserves Medicaid as it stands.
--
-- 🔑 WHY SEASON 2, and the blanks: Season 1 is closed and is not touched. The 131 rows this pass
-- leaves alone keep their migration-1926 blank, their citations and their preserved reasoning.
--
-- Applied by hand via psql; no migration runner exists in this repo. Guards below fail the whole
-- transaction rather than write a partial result.

-- Freeze the targets ONCE, with the rung each earns and the reason it earns it. 🔴 A predicate
-- re-evaluated after the UPDATE would match nothing and pass vacuously.
CREATE TEMP TABLE mig1928_targets AS
WITH blanked AS (
  SELECT pc.politician_id, pc.topic_id, t.short_title AS topic, pc.reasoning,
         substring(pc.reasoning from '🔑 THE RECORD: (.*?)(?: ⚠ WHAT THIS DOES)') AS record_txt
    FROM inform.politician_context pc
    JOIN inform.compass_topics t ON t.id = pc.topic_id
    JOIN inform.politician_answers pa
      ON pa.politician_id = pc.politician_id AND pa.topic_id = pc.topic_id AND pa.season_id = pc.season_id
   WHERE pc.season_id = '86d893a1-c1a2-4bbf-b4e5-69ec43221194'::uuid
     AND pc.reasoning LIKE 'INTERNAL RECORD - blanked by migration 1926%'
     AND pa.value = 0
)
SELECT politician_id, topic_id, topic, record_txt, grp, new_value, rationale
  FROM blanked
  CROSS JOIN LATERAL (
    SELECT * FROM (VALUES
      ('voting-rights', 4,
       'RE-SEATED from blank by migration 1928, on the re-read migration 1926 called for. Rung 4 reads "Require photo ID in person and AN ID NUMBER ON EVERY MAIL BALLOT", and the instrument is a vote FOR the 2021 election bill, which the record below describes as the bill "which requires an ID number on every mail ballot". The rung''s distinguishing clause IS the bill''s mechanism, so this is not a direction-only seat. Rung 5 (documentary proof of citizenship to register) is not in that bill; rung 3''s affidavit alternative is not what the member voted for.')
    ) v(grp, new_value, rationale)
     WHERE topic = 'Voting Rights' AND reasoning LIKE '%87(2) SB1, voted for the 2021 election bill%'
    UNION ALL
    SELECT * FROM (VALUES
      ('redistricting', 5,
       'RE-SEATED from blank by migration 1928, on the re-read migration 1926 called for. Rung 5 reads "the party that controls the state legislature WITHOUT OUTSIDE INTERFERENCE", and the instrument is a vote FOR the 2025 MID-DECADE congressional map drawn by the legislative majority — a redraw outside the decennial cycle, by the controlling party, with no commission and no court mandate. That is the rung''s own text in practice. Rung 4 asserts state legislatures WITH COURT OVERSIGHT TO PREVENT EXTREME PARTISAN BIAS, which a vote for that map is not.')
    ) v(grp, new_value, rationale)
     WHERE topic = 'Redistricting' AND reasoning LIKE '%voted for the 2025 mid-decade congressional map%'
    UNION ALL
    SELECT * FROM (VALUES
      ('same-sex-marriage', 3,
       'RE-SEATED from blank by migration 1928, on the re-read migration 1926 called for. Rung 3 reads "Allow same-sex marriage, but PROTECT RELIGIOUS ORGANIZATIONS'' RIGHT TO DECLINE TO PERFORM OR HOST THESE MARRIAGES", and the instrument below is a bill doing precisely that, by its own caption. Rung 2 is excluded by the carve-out itself; rung 4 (civil unions only) and rung 5 (ban) describe instruments nobody here filed. ⚠ RESERVATION STATED RATHER THAN HIDDEN: filing an exemption bill establishes the exemption position and does not by itself prove the author would vote to keep marriage legal. Rung 3 is nevertheless the only rung of the five whose text this instrument states, which is the test this re-read applies; a reader who disagrees should return the row to blank rather than move it along the ladder.')
    ) v(grp, new_value, rationale)
     WHERE topic = 'Same-Sex Marriage'
    UNION ALL
    SELECT * FROM (VALUES
      ('religious-freedom', 4,
       'RE-SEATED from blank by migration 1928, on the re-read migration 1926 called for. Rung 4 reads "protect religious freedom and allow FAITH-BASED EXEMPTIONS FROM LAWS THAT CONFLICT WITH SINCERE RELIGIOUS BELIEFS", and that is what the instrument below does — the phrase appears in the bills'' own captions, whether the conflicting law concerns a marriage, a service a person or facility declines to take part in, or the closure of a place of worship. Rung 5 requires religious organisations be given COMPLETE AUTONOMY IN THEIR OPERATIONS AND HIRING PRACTICES, which none of these bills grants; rung 3''s balance against equal treatment is excluded, because the instrument resolves the conflict in favour of the exemption.')
    ) v(grp, new_value, rationale)
     WHERE topic = 'Religious Freedom'
    UNION ALL
    SELECT * FROM (VALUES
      ('school-vouchers', 2,
       'RE-SEATED from blank by migration 1928, on the re-read migration 1926 called for. Rung 2 reads "Opposing voucher programs and BLOCKING THEIR EXPANSION, WITHOUT MOVING TO ELIMINATE EXISTING ONES", and the instrument is a vote AGAINST the bill CREATING the education savings account programme. Texas had no such programme to eliminate when the vote was cast, so the vote is a block and cannot establish rung 1''s elimination of an existing programme. This is an affirmative match on rung 2''s own wording, not a choice of the least extreme rung.')
    ) v(grp, new_value, rationale)
     WHERE topic = 'School Vouchers' AND reasoning LIKE '%voted against creating the education savings account program%'
    UNION ALL
    SELECT * FROM (VALUES
      ('healthcare-prohibit', 4,
       'RE-SEATED from blank by migration 1928, on the re-read migration 1926 called for. Rung 4 reads "ONLY HELP THE POOREST PEOPLE afford healthcare and leave everyone else to employers and private insurance", and the instrument is a constitutional amendment, authored by this member, PROHIBITING the state from expanding Medicaid eligibility. A constitutional bar on expansion asserts exactly the ceiling rung 4 names — which is why this row is re-seated while the fourteen rows FILING Medicaid expansion are not: an expansion bill proves a floor and never a ceiling. Rung 5 ("stay out of healthcare entirely") is excluded, because the amendment leaves Medicaid in place as it stands.')
    ) v(grp, new_value, rationale)
     WHERE topic = 'Healthcare' AND reasoning LIKE '%HJR 130%'
  ) pick;

-- GUARD 1 — the groups are exactly what the re-read found. 🔴 Staleness gate.
DO $$
DECLARE n int;
BEGIN
  SELECT count(*) INTO n FROM mig1928_targets;
  IF n <> 34 THEN RAISE EXCEPTION 'migration 1928: expected 34 re-seats, found % — re-measure', n; END IF;
  SELECT count(*) INTO n FROM (SELECT DISTINCT politician_id, topic_id FROM mig1928_targets) s;
  IF n <> 34 THEN RAISE EXCEPTION 'migration 1928: duplicate (politician, topic) pairs; % distinct of 34', n; END IF;
  IF (SELECT count(*) FROM mig1928_targets WHERE grp='voting-rights')     <> 5  THEN RAISE EXCEPTION 'migration 1928: voting-rights group is not 5'; END IF;
  IF (SELECT count(*) FROM mig1928_targets WHERE grp='redistricting')     <> 14 THEN RAISE EXCEPTION 'migration 1928: redistricting group is not 14'; END IF;
  IF (SELECT count(*) FROM mig1928_targets WHERE grp='same-sex-marriage') <> 5  THEN RAISE EXCEPTION 'migration 1928: same-sex-marriage group is not 5'; END IF;
  IF (SELECT count(*) FROM mig1928_targets WHERE grp='religious-freedom') <> 6  THEN RAISE EXCEPTION 'migration 1928: religious-freedom group is not 6'; END IF;
  IF (SELECT count(*) FROM mig1928_targets WHERE grp='school-vouchers')   <> 3  THEN RAISE EXCEPTION 'migration 1928: school-vouchers group is not 3'; END IF;
  IF (SELECT count(*) FROM mig1928_targets WHERE grp='healthcare-prohibit') <> 1 THEN RAISE EXCEPTION 'migration 1928: healthcare-prohibit group is not 1'; END IF;
  -- Every target must carry a parsed instrument to quote forward.
  SELECT count(*) INTO n FROM mig1928_targets WHERE coalesce(record_txt,'') = '';
