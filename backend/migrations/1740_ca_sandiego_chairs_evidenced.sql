     OR c.reasoning IS DISTINCT FROM i.reasoning
     OR c.sources IS DISTINCT FROM i.sources;
  IF bad > 0 THEN RAISE EXCEPTION 'guard 1 failed: % row(s) not as intended', bad; END IF;
END $$;

