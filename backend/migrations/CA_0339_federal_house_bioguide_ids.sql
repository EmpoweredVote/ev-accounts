DECLARE n_set int; n_clash int; n_seat int;
BEGIN
  SELECT count(*) INTO n_set FROM ca0339_ids i JOIN essentials.politicians p ON p.id = i.politician_id AND p.bioguide_id = i.bioguide_id;
  SELECT count(*) INTO n_clash FROM ca0339_ids i JOIN essentials.politicians p ON p.bioguide_id = i.bioguide_id AND p.id <> i.politician_id;
  SELECT count(*) INTO n_seat FROM ca0339_ids i
    JOIN essentials.office_current_holder och ON och.politician_id = i.politician_id
    JOIN essentials.offices o ON o.id = och.office_id
    JOIN essentials.districts d ON d.id = o.district_id AND d.district_type = 'NATIONAL_LOWER' AND d.geo_id = i.seat;
  IF n_set <> 401 THEN RAISE EXCEPTION 'CA_0339: % of 401 rows carry their bioguide id', n_set; END IF;
