-- ---------------------------------------------------------------------------------------
-- chambers.slug is a GENERATED column derived from name_formal (NOT name), so it is not
-- listed here - inserting into it raises 428C9. Setting name_formal is what produces the
-- slug the app routes on; leaving it NULL would generate an empty slug. For legislative
-- chambers GA/NC/UT all carry name = name_formal.
INSERT INTO essentials.chambers (government_id, name, name_formal, official_count, term_length)
SELECT g.id, v.name, v.name, v.official_count, v.term_length
  FROM essentials.governments g
  CROSS JOIN (VALUES
    ('Tennessee House of Representatives', 99::bigint, '2'),
    ('Tennessee Senate', 33::bigint, '4')
  ) AS v(name, official_count, term_length)
 WHERE g.geo_id = '47' AND g.type = 'STATE';

