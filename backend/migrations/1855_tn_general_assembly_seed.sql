-- Migration 1855: seed the Tennessee General Assembly (99 House + 33 Senate)
--
-- Gives the live Nashville landing chip a populated State band. Before this migration the
-- TN state tier held exactly one chamber, one office and one occupant (the Governor), and
-- no STATE_LOWER/STATE_UPPER districts existed at all.
--
-- THE THIN EXECUTIVE BAND IS CORRECT AND IS DELIBERATELY LEFT ALONE.
-- Tennessee popularly elects only the Governor. Verified against the enacted text of the
-- state constitution (Tennessee Blue Book, publications.tnsosfiles.com, retrieved 2026-09-11):
--   Art. III Sec. 2/4 - the governor is chosen by the electors; 4-year term.
--   Art. III Sec. 17  - "A secretary of state shall be appointed by joint vote of the
--                       General Assembly" (4 years).
--   Art. VII Sec. 3   - treasurer and comptroller of the treasury "appointed for the state,
--                       by the joint vote of both Houses" (2 years).
--   Art. VI Sec. 5    - "An attorney general and reporter for the state, shall be appointed
--                       by the judges of the Supreme Court" (8 years).
--   Lieutenant Governor is not a constitutional office; TCA 8-2-102 (Acts 1951 ch. 49 s.2)
--   gives the title to the Senate Speaker, who is chosen by senators.
-- Mirroring Georgia's or North Carolina's four-to-five-seat executive row here would invent
-- popular elections that do not exist. DO NOT "FIX" THE ONE-OFFICE EXEC BAND.
--
-- Chamber sizes: Art. II Sec. 5 fixes the House at ninety-nine. Art. II Sec. 6 caps the
-- Senate at one-third of that; the standing figure of 33 comes from the apportionment act
-- and is confirmed by the directory below listing districts 1-33. Terms: Art. II Sec. 3,
-- two years for representatives and four for senators.
--
-- CASE TRAP: essentials.districts stores LEGISLATIVE district rows with a LOWERCASE state
-- code ('ga', 'nc', 'ut' -- and now 'tn') while NATIONAL_LOWER, NATIONAL_UPPER and
-- STATE_EXEC use uppercase. A verification query filtering state = 'TN' reports ZERO
-- legislative districts even after a perfectly good seed. Every check below uses ILIKE.
--
-- Roster source (both chambers, retrieved 2026-09-11, 114th General Assembly):
--   https://wapp.capitol.tn.gov/apps/LegislatorInfo/Directory?chamber=H
--   https://wapp.capitol.tn.gov/apps/LegislatorInfo/Directory?chamber=S
-- House District 84 is listed as Vacant by that directory, so its office is seeded with
-- is_vacant = true and NO office_terms row - the same shape Georgia Senate District 12
-- already uses.
-- 132 offices, 131 occupants.
--
-- term_start is left NULL with start_precision 'unknown'. The directory publishes no
-- assumed-office date, and the corpus semantic for this column is when the person took THIS
-- seat (cf. NC, where dates were cross-checked per member against Ballotpedia). Inventing a
-- date from the election calendar would mix semantics silently. NULL term_start still passes
-- essentials.current_office_holders. Populating them is owed follow-up work.
--
-- 🔴 ROUTING IS NOT WIRED UP. THIS SEED ALONE DOES NOT MAKE A LEGISLATOR REACHABLE.
-- essentials.geofence_boundaries DOES carry state-legislative polygons (G5210/G5220), for 19
-- states - including Georgia (236) and North Carolina (170). Tennessee has ZERO; its only
-- geofences are G4000/G4020/G5200/G5200V26/G6350. Measured after this migration applied:
-- POST /essentials/browse/by-government-list for Nashville returns "State of Tennessee: 1"
-- (the Governor), while the same call for Columbus GA returns 5 State House + 2 State Senate
-- members, routed by polygon. So these 132 offices are real and correct but not yet reachable
-- from an address or a landing chip.
-- Loading the polygons is a SEPARATE job: backend/scripts/load-state-tiger-boundaries.ts, which
-- requires adding TN to its STATE_LAYER_ALLOWLIST - a deliberate code change, because the
-- allowlist exists to force an explicit per-state review. Confirm FIRST that the TIGER vintage
-- matches Tennessee's current legislative map: routing a voter to the WRONG legislator is worse
-- than routing them to none.
--
-- Generated by backend/scripts/tn-general-assembly-seed-generate.py.
-- No migration runner exists; this file records SQL applied by hand as postgres via the
-- supabase-local MCP. Verified on row counts, not on absence of an error.

