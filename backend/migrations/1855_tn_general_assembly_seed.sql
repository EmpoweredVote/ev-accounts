       d.ocd_id IN ('ocd-division/country:us/state:tn/sldl:84')
  FROM essentials.districts d
  JOIN essentials.chambers c ON c.name = 'Tennessee House of Representatives'
   AND c.government_id = (SELECT id FROM essentials.governments WHERE geo_id = '47' AND type = 'STATE')
 WHERE d.district_type = 'STATE_LOWER' AND d.state = 'tn';

INSERT INTO essentials.offices (chamber_id, district_id, title, representing_state, seats,
