DECLARE v_gov uuid; n bigint;
BEGIN
  SELECT id INTO v_gov FROM essentials.governments WHERE geo_id = '47' AND type = 'STATE';
  IF v_gov IS NULL THEN
    RAISE EXCEPTION 'Migration 1855: State of Tennessee government (geo_id 47) not found';
  END IF;

  SELECT count(*) INTO n FROM essentials.districts
   WHERE district_type IN ('STATE_LOWER','STATE_UPPER') AND state ILIKE 'tn';
  IF n <> 0 THEN
    RAISE EXCEPTION 'Migration 1855: expected 0 pre-existing TN legislative districts, found %', n;
  END IF;

  SELECT count(*) INTO n FROM essentials.politicians
   WHERE external_id BETWEEN -4729999 AND -4710000;
  IF n <> 0 THEN
    RAISE EXCEPTION 'Migration 1855: external_id band -4729999..-4710000 is not free, found %', n;
  END IF;

  SELECT count(*) INTO n FROM essentials.chambers
   WHERE government_id = v_gov AND name IN ('Tennessee House of Representatives', 'Tennessee Senate');
  IF n <> 0 THEN
    RAISE EXCEPTION 'Migration 1855: TN legislative chambers already exist, found %', n;
  END IF;
END
$guard$;

