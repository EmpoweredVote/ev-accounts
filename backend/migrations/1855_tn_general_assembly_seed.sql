-- ---------------------------------------------------------------------------------------
-- 6. Post-conditions -- counted with ILIKE so the lowercase/uppercase split cannot hide a
--    partial seed behind a confident zero.
-- ---------------------------------------------------------------------------------------
DO $verify$
DECLARE n bigint;
BEGIN
  SELECT count(*) INTO n FROM essentials.districts
   WHERE district_type = 'STATE_LOWER' AND state ILIKE 'tn';
  IF n <> 99 THEN RAISE EXCEPTION 'Migration 1855: expected 99 STATE_LOWER districts, got %', n; END IF;
  SELECT count(*) INTO n FROM essentials.districts
   WHERE district_type = 'STATE_UPPER' AND state ILIKE 'tn';
  IF n <> 33 THEN RAISE EXCEPTION 'Migration 1855: expected 33 STATE_UPPER districts, got %', n; END IF;

  SELECT count(*) INTO n FROM essentials.offices o
    JOIN essentials.districts d ON d.id = o.district_id
   WHERE d.state ILIKE 'tn' AND d.district_type IN ('STATE_LOWER','STATE_UPPER');
  IF n <> 132 THEN RAISE EXCEPTION 'Migration 1855: expected 132 TN legislative offices, got %', n; END IF;

  SELECT count(*) INTO n FROM essentials.districts d
    JOIN essentials.offices o ON o.district_id = d.id
   WHERE d.state ILIKE 'tn' AND d.district_type IN ('STATE_LOWER','STATE_UPPER')
   GROUP BY d.id HAVING count(o.id) <> 1 LIMIT 1;
  IF FOUND THEN RAISE EXCEPTION 'Migration 1855: a TN legislative district does not have exactly one office'; END IF;

  SELECT count(*) INTO n FROM essentials.current_office_holders coh
    JOIN essentials.offices o ON o.id = coh.office_id
