-- every one of them with no gaps), so generate_series cannot silently omit a district the
-- way a hand-written VALUES list can.
INSERT INTO essentials.districts (district_type, label, state, ocd_id, mtfcc, geo_id, representation_basis)
SELECT 'STATE_LOWER', 'State House District ' || n, 'tn',
       'ocd-division/country:us/state:tn/sldl:' || n, 'G5220', '47' || lpad(n::text, 3, '0'), 'residency'
  FROM generate_series(1, 99) AS n
UNION ALL
SELECT 'STATE_UPPER', 'State Senate District ' || n, 'tn',
       'ocd-division/country:us/state:tn/sldu:' || n, 'G5210', '47' || lpad(n::text, 3, '0'), 'residency'
  FROM generate_series(1, 33) AS n;

