/** Host -> middle certificates its server leaves out. */
const MISSING_INTERMEDIATES: Record<string, string[]> = {
  'www.legislature.ohio.gov': [SECTIGO_PUBLIC_SERVER_AUTHENTICATION_CA_OV_R36],
};

/** The CA list to use for a host: null for every host that needs none (use the global fetch). */
export function extraTrustFor(host: string): string[] | null {
  const extra = MISSING_INTERMEDIATES[host.toLowerCase()];
  return extra ? [...tls.rootCertificates, ...extra] : null;
}

/** A GET through node:https with the given CA list. Follows no redirect (the caller sees the 3xx). */
function getWithCa(url: string, ca: string[], init: RequestInit = {}): Promise<Response> {
  return new Promise((resolve, reject) => {
    const headers = Object.fromEntries(new Headers(init.headers).entries());
    const req = https.get(url, { ca, headers, signal: init.signal ?? undefined }, (res) => {
      const chunks: Buffer[] = [];
      res.on('data', (c: Buffer) => chunks.push(c));
      res.on('error', reject);
      res.on('end', () => {
        const h = new Headers();
        for (const [k, v] of Object.entries(res.headers)) if (v !== undefined) h.set(k, Array.isArray(v) ? v.join(', ') : String(v));
        resolve(new Response(Buffer.concat(chunks), { status: res.statusCode ?? 0, headers: h }));
      });
    });
    req.on('error', reject);
  });
}

/** The global fetch, except for a host listed above, which is fetched with its missing middle certificate added. */
export const fetchWithHostTrust: FetchLike = (url, init) => {
  let host = '';
  try { host = new URL(url).host; } catch { /* the global fetch reports it */ }
  const ca = host ? extraTrustFor(host) : null;
  return ca ? getWithCa(url, ca, init) : fetch(url, init);
};
