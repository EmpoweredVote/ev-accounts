// ---------------------------------------------------------------------------
// Seed execution
// ---------------------------------------------------------------------------

async function main() {
  console.log('[seedPoliticians] Starting politician seed...');
  console.log(`[seedPoliticians] Records to upsert: ${seedRecords.length}`);

  const { data, error } = await supabase
    .schema('inform')
    .from('politicians')
    .upsert(seedRecords, {
      onConflict: 'first_name,last_name',
      ignoreDuplicates: false,
    })
    .select('id, office_title, district_type, district_id');

  if (error) {
    console.error('[seedPoliticians] ERROR during upsert:', error.message);
    console.error('[seedPoliticians] Details:', error);
    process.exit(1);
  }

  console.log('[seedPoliticians] Upsert complete. Records written:');
  for (const row of data ?? []) {
    console.log(
      `  - [${row.district_type ?? 'unknown'}] ${row.office_title ?? row.id} (district_id: ${row.district_id ?? 'none'})`
    );
  }

  console.log('[seedPoliticians] Done.');
  process.exit(0);
}

main().catch((err: unknown) => {
  console.error('[seedPoliticians] Unexpected error:', err);
  process.exit(1);
});
